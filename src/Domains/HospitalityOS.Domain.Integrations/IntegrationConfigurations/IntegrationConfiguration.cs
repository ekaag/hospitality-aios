using HospitalityOS.Domain.Integrations.IntegrationConfigurations.Events;
using HospitalityOS.Domain.Integrations.Shared;
using HospitalityOS.SharedKernel.Collections;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Integrations.IntegrationConfigurations;

/// <summary>
/// Which provider serves one kind of connector for one property, with the provider's settings, e.g. Aurora Grand's
/// PMS is <c>MockPms</c>. Swapping a provider changes only this record, never domain or capability code (Journey 18).
/// One per property and kind.
/// </summary>
/// <remarks>
/// Settings are not secret: they name secrets kept in the secret store, never hold them (P10).
/// </remarks>
public sealed class IntegrationConfiguration : AggregateRoot<IntegrationConfigurationId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Longest provider name.
    /// </summary>
    public const int MaxProviderNameLength = 64;

    /// <summary>
    /// Most settings one configuration may hold.
    /// </summary>
    public const int MaxSettings = 50;

    /// <summary>
    /// Longest setting name.
    /// </summary>
    public const int MaxSettingNameLength = 64;

    /// <summary>
    /// Longest setting value.
    /// </summary>
    public const int MaxSettingValueLength = 2000;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private IntegrationConfiguration()
    {
        ProviderName = null!;
        Settings = null!;
    }

    private IntegrationConfiguration(
        IntegrationConfigurationId id,
        TenantId tenantId,
        PropertyId propertyId,
        ConnectorKind kind,
        string providerName,
        ValueList<IntegrationSetting> settings)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Kind = kind;
        ProviderName = providerName;
        Settings = settings;
        Status = IntegrationStatus.Active;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property served.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Which connector this configures; fixed.
    /// </summary>
    public ConnectorKind Kind { get; }

    /// <summary>
    /// The provider's registered name, e.g. <c>MockPms</c>.
    /// </summary>
    public string ProviderName { get; private set; }

    /// <summary>
    /// The provider's settings, ordered by name; names are unique ignoring case.
    /// </summary>
    public ValueList<IntegrationSetting> Settings { get; private set; }

    /// <summary>
    /// Whether the connector may be used.
    /// </summary>
    public IntegrationStatus Status { get; private set; }

    /// <summary>
    /// Whether the connector may be used.
    /// </summary>
    public bool IsActive => Status == IntegrationStatus.Active;

    /// <summary>
    /// Creates an active configuration and raises <see cref="IntegrationConfigurationCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property served.</param>
    /// <param name="kind">Which connector this configures.</param>
    /// <param name="providerName">The provider's registered name; the caller checks it is registered.</param>
    /// <param name="settings">The provider's settings; the caller checks them with the provider.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The configuration, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<IntegrationConfiguration> Create(
        IntegrationConfigurationId id,
        TenantId tenantId,
        PropertyId propertyId,
        ConnectorKind kind,
        string providerName,
        IEnumerable<IntegrationSetting> settings,
        DateTimeOffset now)
    {
        List<FieldError> errors = [];

        if (!Enum.IsDefined(kind))
        {
            errors.Add(new FieldError("kind", "integration.kind_invalid", $"'{kind}' is not a known connector kind."));
        }

        string provider = IntegrationRules.ProviderName(providerName, errors);
        ValueList<IntegrationSetting> validSettings = ValidateSettings(settings, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        IntegrationConfiguration configuration = new(id, tenantId, propertyId, kind, provider, validSettings);
        configuration.Raise(new IntegrationConfigurationCreated(id, propertyId, kind, provider, configuration.Status, now));

        return configuration;
    }

    /// <summary>
    /// Switches provider or changes settings and raises <see cref="IntegrationConfigurationUpdated"/>. Reconfiguring
    /// to the current provider and settings is a no-op (P8).
    /// </summary>
    /// <param name="providerName">The provider's registered name; the caller checks it is registered.</param>
    /// <param name="settings">The provider's settings; the caller checks them with the provider.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Reconfigure(string providerName, IEnumerable<IntegrationSetting> settings, DateTimeOffset now)
    {
        List<FieldError> errors = [];
        string provider = IntegrationRules.ProviderName(providerName, errors);
        ValueList<IntegrationSetting> validSettings = ValidateSettings(settings, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        if (provider == ProviderName && validSettings == Settings)
        {
            return Result.Success();
        }

        ProviderName = provider;
        Settings = validSettings;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Stops the connector being used and raises <see cref="IntegrationConfigurationUpdated"/>. Disabling twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    public void Disable(DateTimeOffset now) => ChangeStatus(IntegrationStatus.Disabled, now);

    /// <summary>
    /// Lets the connector be used again and raises <see cref="IntegrationConfigurationUpdated"/>. Enabling twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    public void Enable(DateTimeOffset now) => ChangeStatus(IntegrationStatus.Active, now);

    private void ChangeStatus(IntegrationStatus status, DateTimeOffset now)
    {
        if (Status == status)
        {
            return;
        }

        Status = status;
        RaiseUpdated(now);
    }

    private void RaiseUpdated(DateTimeOffset now) =>
        Raise(new IntegrationConfigurationUpdated(Id, Kind, ProviderName, Status, now));

    private static ValueList<IntegrationSetting> ValidateSettings(IEnumerable<IntegrationSetting> settings, List<FieldError> errors)
    {
        ArgumentNullException.ThrowIfNull(settings);

        List<IntegrationSetting> valid = [];
        HashSet<string> names = new(StringComparer.OrdinalIgnoreCase);
        int index = 0;

        foreach (IntegrationSetting setting in settings)
        {
            string field = $"settings[{index++}]";
            string name = IntegrationRules.SettingName(setting.Name, field + ".name", errors);

            if (setting.Value is null)
            {
                errors.Add(new FieldError(field + ".value", "integration.setting_value_required", "A setting needs a value."));
            }
            else if (setting.Value.Length > MaxSettingValueLength)
            {
                errors.Add(new FieldError(field + ".value", "integration.setting_value_too_long", $"A setting value may be at most {MaxSettingValueLength} characters."));
            }

            if (name.Length > 0 && !names.Add(name))
            {
                errors.Add(new FieldError(field + ".name", "integration.setting_duplicate", $"Setting '{name}' appears more than once."));
            }

            valid.Add(new IntegrationSetting(name, setting.Value ?? ""));
        }

        if (valid.Count > MaxSettings)
        {
            errors.Add(new FieldError("settings", "integration.settings_too_many", $"A configuration may have at most {MaxSettings} settings."));
        }

        return ValueList.From(valid.OrderBy(setting => setting.Name, StringComparer.OrdinalIgnoreCase));
    }
}
