using HospitalityOS.Domain.Integrations.ExternalReferences.Events;
using HospitalityOS.Domain.Integrations.Shared;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Integrations.ExternalReferences;

/// <summary>
/// Links a provider's ID for a record to the record's canonical ID, e.g. MockPms reservation <c>RES-0412</c> to a
/// <c>StayContext</c> (P3). Canonical IDs never change: when a property swaps provider, the new provider's IDs get
/// new references to the same canonical records, and the old ones stay as history (Journey 18). Immutable.
/// </summary>
public sealed class ExternalReference : AggregateRoot<ExternalReferenceId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Longest canonical type name.
    /// </summary>
    public const int MaxEntityTypeLength = 64;

    /// <summary>
    /// Longest provider ID; equal to <c>ExternalId.MaxLength</c> in the integration contracts.
    /// </summary>
    public const int MaxExternalIdLength = 256;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private ExternalReference()
    {
        ProviderName = null!;
        EntityType = null!;
        ExternalId = null!;
    }

    private ExternalReference(
        ExternalReferenceId id,
        TenantId tenantId,
        PropertyId propertyId,
        string providerName,
        string entityType,
        string externalId,
        Guid canonicalId)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        ProviderName = providerName;
        EntityType = entityType;
        ExternalId = externalId;
        CanonicalId = canonicalId;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property whose provider issued the ID.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The provider's registered name, e.g. <c>MockPms</c>.
    /// </summary>
    public string ProviderName { get; }

    /// <summary>
    /// The canonical record's type name, e.g. <c>StayContext</c>.
    /// </summary>
    public string EntityType { get; }

    /// <summary>
    /// The provider's ID, exactly as issued.
    /// </summary>
    public string ExternalId { get; }

    /// <summary>
    /// The canonical record's ID.
    /// </summary>
    public Guid CanonicalId { get; }

    /// <summary>
    /// Creates a reference and raises <see cref="ExternalReferenceCreated"/>. A provider ID maps to one canonical record
    /// per property, provider, and type (enforced on commit); a canonical record may have IDs from several providers.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property whose provider issued the ID.</param>
    /// <param name="providerName">The provider's registered name.</param>
    /// <param name="entityType">The canonical record's type name.</param>
    /// <param name="externalId">The provider's ID, kept exactly.</param>
    /// <param name="canonicalId">The canonical record's ID.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The reference, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<ExternalReference> Create(
        ExternalReferenceId id,
        TenantId tenantId,
        PropertyId propertyId,
        string providerName,
        string entityType,
        string externalId,
        Guid canonicalId,
        DateTimeOffset now)
    {
        List<FieldError> errors = [];
        string provider = IntegrationRules.ProviderName(providerName, errors);
        string type = IntegrationRules.TypeName(entityType, "entityType", "integration.entity_type", MaxEntityTypeLength, errors);

        if (string.IsNullOrWhiteSpace(externalId))
        {
            errors.Add(new FieldError("externalId", "integration.external_id_required", "externalId is required."));
        }
        else if (externalId.Length > MaxExternalIdLength)
        {
            errors.Add(new FieldError("externalId", "integration.external_id_too_long", $"externalId must be at most {MaxExternalIdLength} characters."));
        }

        if (canonicalId == Guid.Empty)
        {
            errors.Add(new FieldError("canonicalId", "integration.canonical_id_required", "canonicalId is required."));
        }

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        ExternalReference reference = new(id, tenantId, propertyId, provider, type, externalId, canonicalId);
        reference.Raise(new ExternalReferenceCreated(id, propertyId, provider, type, externalId, canonicalId, now));

        return reference;
    }
}
