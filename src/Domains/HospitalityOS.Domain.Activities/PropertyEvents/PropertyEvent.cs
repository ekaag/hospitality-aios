using HospitalityOS.Domain.Activities.PropertyEvents.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Pricing;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Activities.PropertyEvents;

/// <summary>
/// Something happening at the property, e.g. live music or a yoga class (Journey 8). Named PropertyEvent to
/// avoid confusion with domain events. Times are property-local, like operating hours.
/// </summary>
public sealed class PropertyEvent : AggregateRoot<PropertyEventId>, ITenantScoped
{
    /// <summary>
    /// Longest allowed event; guards against date typos.
    /// </summary>
    public static TimeSpan MaxDuration { get; } = TimeSpan.FromDays(14);

    private PropertyEvent(PropertyEventId id, TenantId tenantId, PropertyId propertyId, PropertyEventDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
        Status = PropertyEventStatus.Scheduled;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property hosting the event.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized information.
    /// </summary>
    public PropertyEventDetails Details { get; private set; }

    /// <summary>
    /// Whether the event is going ahead.
    /// </summary>
    public PropertyEventStatus Status { get; private set; }

    /// <summary>
    /// Creates a scheduled event and raises <see cref="PropertyEventCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property hosting the event.</param>
    /// <param name="details">Information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The event, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<PropertyEvent> Create(PropertyEventId id, TenantId tenantId, PropertyId propertyId, PropertyEventDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<PropertyEventDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        PropertyEvent propertyEvent = new(id, tenantId, propertyId, valid.Value);
        propertyEvent.Raise(new PropertyEventCreated(id, propertyId, propertyEvent.Details, propertyEvent.Status, now));

        return propertyEvent;
    }

    /// <summary>
    /// Replaces the information and raises <see cref="PropertyEventUpdated"/>. A no-change update is a no-op (P8).
    /// </summary>
    /// <param name="details">New information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, a <see cref="ValidationError"/>, or an <see cref="ErrorKind.InvalidState"/> error when cancelled.</returns>
    public Result Update(PropertyEventDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        if (Status == PropertyEventStatus.Cancelled)
        {
            return Error.InvalidState("property_event.cancelled", "A cancelled event cannot be changed; create a new event instead.");
        }

        Result<PropertyEventDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Calls the event off and raises <see cref="PropertyEventUpdated"/>; it is no longer offered to guests.
    /// Cancelling twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success.</returns>
    public Result Cancel(DateTimeOffset now)
    {
        if (Status != PropertyEventStatus.Cancelled)
        {
            Status = PropertyEventStatus.Cancelled;
            RaiseUpdated(now);
        }

        return Result.Success();
    }

    /// <summary>
    /// Whether the event can still be offered at a property-local time: scheduled and not yet ended
    /// (ongoing events count). Past events are never offered (Journey 8).
    /// </summary>
    /// <param name="localNow">The current property-local time.</param>
    public bool IsUpcomingOrOngoingAt(DateTime localNow) =>
        Status == PropertyEventStatus.Scheduled && Details.LocalEnd > localNow;

    /// <summary>
    /// Whether the event is upcoming or ongoing at <paramref name="localNow"/> and passes <paramref name="filter"/>.
    /// </summary>
    /// <param name="localNow">The current property-local time.</param>
    /// <param name="filter">Time, category, and audience narrowing.</param>
    public bool Matches(DateTime localNow, PropertyEventFilter filter)
    {
        ArgumentNullException.ThrowIfNull(filter);

        return IsUpcomingOrOngoingAt(localNow)
            && (filter.LocalFrom is null || Details.LocalEnd > filter.LocalFrom)
            && (filter.LocalTo is null || Details.LocalStart < filter.LocalTo)
            && (filter.Category is null || Details.Category == filter.Category)
            && (filter.Audience is null || Details.Audience == EventAudience.Everyone || Details.Audience == filter.Audience);
    }

    /// <summary>
    /// Selects the events a guest may be offered now, earliest first: upcoming or ongoing in the property's
    /// time zone and passing <paramref name="filter"/>.
    /// </summary>
    /// <param name="events">Candidate events of one property.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <param name="propertyTimeZone">The property's time zone (from <c>Property.Details.TimeZoneId</c>).</param>
    /// <param name="filter">Time, category, and audience narrowing; <c>null</c> for none.</param>
    public static IReadOnlyList<PropertyEvent> SelectUpcoming(
        IEnumerable<PropertyEvent> events,
        DateTimeOffset now,
        TimeZoneInfo propertyTimeZone,
        PropertyEventFilter? filter = null)
    {
        ArgumentNullException.ThrowIfNull(events);
        ArgumentNullException.ThrowIfNull(propertyTimeZone);

        DateTime localNow = TimeZoneInfo.ConvertTime(now, propertyTimeZone).DateTime;
        PropertyEventFilter applied = filter ?? PropertyEventFilter.None;

        return [.. events
            .Where(candidate => candidate.Matches(localNow, applied))
            .OrderBy(candidate => candidate.Details.LocalStart)
            .ThenBy(candidate => candidate.Details.Title, StringComparer.Ordinal)];
    }

    private void RaiseUpdated(DateTimeOffset now) => Raise(new PropertyEventUpdated(Id, Details, Status, now));

    private static Result<PropertyEventDetails> Validate(PropertyEventDetails details)
    {
        List<FieldError> errors = [];

        string title = TextRules.Required(details.Title, "title", "property_event.title", errors);
        string? description = TextRules.Optional(details.Description, "description", "property_event.description", errors, TextRules.MaxLongTextLength);
        Money? price = details.Price is null ? null : MoneyRules.Validate(details.Price, "price", "property_event.price", errors);

        if (!Enum.IsDefined(details.Category))
        {
            errors.Add(new FieldError("category", "property_event.category_invalid", $"'{details.Category}' is not a known event category."));
        }

        if (!Enum.IsDefined(details.Audience))
        {
            errors.Add(new FieldError("audience", "property_event.audience_invalid", $"'{details.Audience}' is not a known audience."));
        }

        // Local wall-clock times: drop any Kind so values compare and persist consistently.
        DateTime start = DateTime.SpecifyKind(details.LocalStart, DateTimeKind.Unspecified);
        DateTime end = DateTime.SpecifyKind(details.LocalEnd, DateTimeKind.Unspecified);

        if (end <= start)
        {
            errors.Add(new FieldError("localEnd", "property_event.end_before_start", "localEnd must be after localStart."));
        }
        else if (end - start > MaxDuration)
        {
            errors.Add(new FieldError("localEnd", "property_event.too_long", $"An event may last at most {MaxDuration.TotalDays} days."));
        }

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Title = title, Description = description, Price = price, LocalStart = start, LocalEnd = end };
    }
}
