using HospitalityOS.Domain.Dining.Menus.Events;
using HospitalityOS.Domain.Dining.Restaurants;
using HospitalityOS.SharedKernel.Collections;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Dining.Menus;

/// <summary>
/// A restaurant's menu and its items, edited as one unit so each change raises a single
/// <see cref="MenuUpdated"/> (spec §8). Supports dietary search for Demo 3 ("what vegetarian food can I get?").
/// </summary>
public sealed class Menu : AggregateRoot<MenuId>, ITenantScoped
{
    private Menu(MenuId id, TenantId tenantId, PropertyId propertyId, RestaurantId restaurantId, MenuDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        RestaurantId = restaurantId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the menu's restaurant belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The restaurant serving the menu.
    /// </summary>
    public RestaurantId RestaurantId { get; }

    /// <summary>
    /// Validated, normalized content.
    /// </summary>
    public MenuDetails Details { get; private set; }

    /// <summary>
    /// Creates a menu for a restaurant and raises <see cref="MenuCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="restaurant">The restaurant, loaded by the caller; determines tenant and property.</param>
    /// <param name="details">Content; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The menu, or a <see cref="ValidationError"/> listing every problem.</returns>
    public static Result<Menu> Create(MenuId id, Restaurant restaurant, MenuDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(restaurant);
        ArgumentNullException.ThrowIfNull(details);

        Result<MenuDetails> valid = MenuRules.Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Menu menu = new(id, restaurant.TenantId, restaurant.PropertyId, restaurant.Id, valid.Value);
        menu.Raise(new MenuCreated(id, menu.PropertyId, menu.RestaurantId, menu.Details, now));

        return menu;
    }

    /// <summary>
    /// Replaces the whole menu and raises <see cref="MenuUpdated"/>. A no-change update is a successful no-op (P8).
    /// </summary>
    /// <param name="details">New content; validated and normalized. Keep existing item IDs for unchanged items.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every problem.</returns>
    public Result Update(MenuDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<MenuDetails> valid = MenuRules.Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        return Apply(valid.Value, now);
    }

    /// <summary>
    /// Marks one item available or unavailable (e.g. sold out) and raises <see cref="MenuUpdated"/>.
    /// Setting the current value is a no-op.
    /// </summary>
    /// <param name="itemId">The item.</param>
    /// <param name="isAvailable">Whether it can be ordered.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ErrorKind.NotFound"/> error when the item is not on the menu.</returns>
    public Result SetItemAvailability(MenuItemId itemId, bool isAvailable, DateTimeOffset now)
    {
        if (!Details.Items.Any(item => item.Id == itemId))
        {
            return Error.NotFound("menu.item_not_found", $"Item {itemId} is not on this menu.");
        }

        ValueList<MenuItem> items = ValueList.From(Details.Items.Select(item => item.Id == itemId ? item with { IsAvailable = isAvailable } : item));

        return Apply(Details with { Items = items }, now);
    }

    /// <summary>
    /// Items having every required dietary tag, in menu order; by default only available ones.
    /// </summary>
    /// <param name="required">Tags the item must have, e.g. <see cref="DietaryTag.Vegetarian"/>.</param>
    /// <param name="availableOnly">Whether to skip items marked unavailable.</param>
    public IReadOnlyList<MenuItem> FindItems(IReadOnlyCollection<DietaryTag> required, bool availableOnly = true)
    {
        ArgumentNullException.ThrowIfNull(required);

        return [.. Details.Items.Where(item => (!availableOnly || item.IsAvailable) && item.Has(required))];
    }

    private Result Apply(MenuDetails details, DateTimeOffset now)
    {
        if (details == Details)
        {
            return Result.Success();
        }

        Details = details;
        Raise(new MenuUpdated(Id, Details, now));

        return Result.Success();
    }
}
