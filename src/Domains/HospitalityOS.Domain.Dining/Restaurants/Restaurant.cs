using HospitalityOS.Domain.Dining.Restaurants.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Dining.Restaurants;

/// <summary>
/// A place to eat or drink at the property (Journey 3). Its menus are <see cref="Menus.Menu"/> aggregates.
/// Holds no POS-vendor fields; external identifiers live in <c>ExternalReference</c> (P3).
/// </summary>
public sealed class Restaurant : AggregateRoot<RestaurantId>, ITenantScoped, IPropertyScoped
{
    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private Restaurant()
    {
        Details = null!;
    }

    private Restaurant(RestaurantId id, TenantId tenantId, PropertyId propertyId, RestaurantDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the restaurant belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized descriptive information.
    /// </summary>
    public RestaurantDetails Details { get; private set; }

    /// <summary>
    /// Creates a restaurant and raises <see cref="RestaurantCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the restaurant belongs to.</param>
    /// <param name="details">Descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The restaurant, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Restaurant> Create(RestaurantId id, TenantId tenantId, PropertyId propertyId, RestaurantDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<RestaurantDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Restaurant restaurant = new(id, tenantId, propertyId, valid.Value);
        restaurant.Raise(new RestaurantCreated(id, propertyId, restaurant.Details, now));

        return restaurant;
    }

    /// <summary>
    /// Replaces the descriptive information and raises <see cref="RestaurantUpdated"/>. A no-change update is
    /// a successful no-op (P8).
    /// </summary>
    /// <param name="details">New descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(RestaurantDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<RestaurantDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        Raise(new RestaurantUpdated(Id, Details, now));

        return Result.Success();
    }

    private static Result<RestaurantDetails> Validate(RestaurantDetails details)
    {
        List<FieldError> errors = [];

        string name = TextRules.Required(details.Name, "name", "restaurant.name", errors);
        string? cuisine = TextRules.Optional(details.Cuisine, "cuisine", "restaurant.cuisine", errors);
        string? description = TextRules.Optional(details.Description, "description", "restaurant.description", errors, TextRules.MaxLongTextLength);

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Name = name, Cuisine = cuisine, Description = description };
    }
}
