using HospitalityOS.Domain.Guests.GuestLinks.Events;
using HospitalityOS.Domain.Guests.StayContexts;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Guests.GuestLinks;

/// <summary>
/// A stay's check-in link (K4c): the code a QR code or link carries, which the guest app exchanges for a short-lived stay
/// token on any device, for as long as the stay is reserved or in house and the link is not revoked. Staff replace a
/// link by revoking it and creating another, so a stay has at most one open link. Only the code's hash is kept, and
/// events never carry it.
/// </summary>
public sealed class GuestLink : AggregateRoot<GuestLinkId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Length of <see cref="CodeHash"/>: a SHA-256 hash in lowercase hex.
    /// </summary>
    public const int CodeHashLength = 64;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private GuestLink()
    {
        CodeHash = null!;
    }

    private GuestLink(GuestLinkId id, TenantId tenantId, PropertyId propertyId, StayContextId stayContextId, GuestId guestId, string codeHash, DateTimeOffset createdAt)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        StayContextId = stayContextId;
        GuestId = guestId;
        CodeHash = codeHash;
        CreatedAt = createdAt;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <inheritdoc />
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The stay it opens.
    /// </summary>
    public StayContextId StayContextId { get; }

    /// <summary>
    /// The stay's guest, whom the stay tokens name.
    /// </summary>
    public GuestId GuestId { get; }

    /// <summary>
    /// The hash of the code it carries.
    /// </summary>
    public string? CodeHash { get; private set; }

    /// <summary>
    /// When it was created.
    /// </summary>
    public DateTimeOffset CreatedAt { get; }

    /// <summary>
    /// When it was revoked, after which its code opens nothing.
    /// </summary>
    public DateTimeOffset? RevokedAt { get; private set; }

    /// <summary>
    /// Whether its code still opens the stay (the stay must also still be active).
    /// </summary>
    public bool IsOpen => RevokedAt is null;

    /// <summary>
    /// Creates a link for an active stay and raises <see cref="GuestLinkCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="stay">The stay, which must be reserved or in house.</param>
    /// <param name="codeHash">The hash of the code it carries.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The link; <c>guest_link.stay_ended</c>; or a <see cref="ValidationError"/> for a malformed hash.</returns>
    public static Result<GuestLink> Create(GuestLinkId id, StayContext stay, string codeHash, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(stay);

        if (stay.Status is not (StayStatus.Reserved or StayStatus.InHouse))
        {
            return StayEnded(stay);
        }

        if (codeHash is not { Length: CodeHashLength } || !codeHash.All(c => char.IsAsciiDigit(c) || c is >= 'a' and <= 'f'))
        {
            return Error.Validation("codeHash", "guest_link.code_hash_invalid", $"A link's code hash is {CodeHashLength} lowercase hex digits.");
        }

        GuestLink link = new(id, stay.TenantId, stay.PropertyId, stay.Id, stay.GuestId, codeHash, now);
        link.Raise(new GuestLinkCreated(id, stay.Id, stay.PropertyId, now));
        return link;
    }

    /// <summary>
    /// Stops the code working and raises <see cref="GuestLinkRevoked"/>; revoking again is a successful no-op (P8).
    /// </summary>
    public Result Revoke(DateTimeOffset now)
    {
        if (RevokedAt is not null)
        {
            return Result.Success();
        }

        RevokedAt = now;

        // Freed, so a code cannot open a revoked link even by a lookup that forgets to check.
        CodeHash = null;
        Raise(new GuestLinkRevoked(Id, StayContextId, now));
        return Result.Success();
    }

    /// <summary>
    /// The error for a stay that is no longer reserved or in house.
    /// </summary>
    public static Error StayEnded(StayContext stay)
    {
        ArgumentNullException.ThrowIfNull(stay);
        return Error.InvalidState("guest_link.stay_ended", $"This stay is {stay.Status}; check-in links work only while it is reserved or in house.");
    }
}
