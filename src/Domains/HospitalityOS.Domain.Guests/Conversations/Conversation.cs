using HospitalityOS.Domain.Guests.Conversations.Events;
using HospitalityOS.Domain.Guests.StayContexts;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Guests.Conversations;

/// <summary>
/// A guest's chat thread at a property. Messages are separate <see cref="GuestMessages.GuestMessage"/>
/// aggregates so a long conversation never has to load in full. A conversation may start anonymous and be
/// linked to a stay once the guest is identified.
/// </summary>
public sealed class Conversation : AggregateRoot<ConversationId>, ITenantScoped
{
    // For EF Core only: it sets every property from storage before the instance is used.
    private Conversation()
    {
    }

    private Conversation(ConversationId id, TenantId tenantId, PropertyId propertyId, ConversationChannel channel, DateTimeOffset startedAt)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Channel = channel;
        StartedAt = startedAt;
        Status = ConversationStatus.Open;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the guest is talking to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Where the conversation takes place.
    /// </summary>
    public ConversationChannel Channel { get; }

    /// <summary>
    /// When it started (UTC).
    /// </summary>
    public DateTimeOffset StartedAt { get; }

    /// <summary>
    /// The guest, once identified.
    /// </summary>
    public GuestId? GuestId { get; private set; }

    /// <summary>
    /// The guest's stay, once identified; gives the delivery location for service requests.
    /// </summary>
    public StayContextId? StayContextId { get; private set; }

    /// <summary>
    /// Whether the conversation accepts messages.
    /// </summary>
    public ConversationStatus Status { get; private set; }

    /// <summary>
    /// Starts an open, anonymous conversation and raises <see cref="ConversationStarted"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the guest is talking to.</param>
    /// <param name="channel">Where the conversation takes place.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The conversation, or a <see cref="ValidationError"/>.</returns>
    public static Result<Conversation> Start(ConversationId id, TenantId tenantId, PropertyId propertyId, ConversationChannel channel, DateTimeOffset now)
    {
        if (!Enum.IsDefined(channel))
        {
            return Error.Validation("channel", "conversation.channel_invalid", $"'{channel}' is not a known channel.");
        }

        Conversation conversation = new(id, tenantId, propertyId, channel, now);
        conversation.Raise(new ConversationStarted(id, propertyId, channel, now));

        return conversation;
    }

    /// <summary>
    /// Identifies the guest by linking their stay and raises <see cref="ConversationUpdated"/>. Linking the same
    /// stay again is a no-op; a conversation keeps one guest for life.
    /// </summary>
    /// <param name="stay">The stay, loaded by the caller; must be at this property and, if a guest is already
    /// linked, belong to that guest.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, a <see cref="ValidationError"/>, or an <see cref="ErrorKind.InvalidState"/> error when closed.</returns>
    public Result LinkStay(StayContext stay, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(stay);

        if (Status == ConversationStatus.Closed)
        {
            return ClosedError();
        }

        if (stay.PropertyId != PropertyId || stay.TenantId != TenantId)
        {
            return Error.Validation("stayContextId", "conversation.stay_other_property", "The stay must be at the conversation's property.");
        }

        if (GuestId is not null && stay.GuestId != GuestId)
        {
            return Error.Validation("stayContextId", "conversation.stay_other_guest", "The stay belongs to a different guest than this conversation.");
        }

        if (stay.Id == StayContextId)
        {
            return Result.Success();
        }

        GuestId = stay.GuestId;
        StayContextId = stay.Id;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Ends the conversation and raises <see cref="ConversationUpdated"/>. Closing twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success.</returns>
    public Result Close(DateTimeOffset now)
    {
        if (Status != ConversationStatus.Closed)
        {
            Status = ConversationStatus.Closed;
            RaiseUpdated(now);
        }

        return Result.Success();
    }

    internal static Error ClosedError() =>
        Error.InvalidState("conversation.closed", "The conversation is closed; start a new one.");

    private void RaiseUpdated(DateTimeOffset now) => Raise(new ConversationUpdated(Id, GuestId, StayContextId, Status, now));
}
