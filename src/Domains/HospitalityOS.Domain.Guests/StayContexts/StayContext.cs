using HospitalityOS.Domain.Guests.Guests;
using HospitalityOS.Domain.Guests.StayContexts.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Guests.StayContexts;

/// <summary>
/// One guest's stay at one property: when, and in which unit (e.g. Room 412). The Guest Service controller
/// uses it to know where to deliver and which requests are the guest's (Journeys 9 and 12). In Phase 1 stays
/// are created natively; a PMS connector later supplies them through <c>ExternalReference</c> (P3).
/// </summary>
public sealed class StayContext : AggregateRoot<StayContextId>, ITenantScoped
{
    /// <summary>
    /// Longest allowed stay; guards against date typos.
    /// </summary>
    public const int MaxNights = 365;

    // For EF Core only: it sets every property from storage before the instance is used.
    private StayContext()
    {
    }

    private StayContext(
        StayContextId id,
        TenantId tenantId,
        PropertyId propertyId,
        GuestId guestId,
        DateOnly arrival,
        DateOnly departure,
        AccommodationUnitId? unitId)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        GuestId = guestId;
        Arrival = arrival;
        Departure = departure;
        AccommodationUnitId = unitId;
        Status = StayStatus.Reserved;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property of the stay.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Who is staying.
    /// </summary>
    public GuestId GuestId { get; }

    /// <summary>
    /// Property-local arrival date.
    /// </summary>
    public DateOnly Arrival { get; private set; }

    /// <summary>
    /// Property-local departure date; after <see cref="Arrival"/>.
    /// </summary>
    public DateOnly Departure { get; private set; }

    /// <summary>
    /// The assigned unit, once known (checked to be in the same property by the application layer).
    /// </summary>
    public AccommodationUnitId? AccommodationUnitId { get; private set; }

    /// <summary>
    /// Where the stay is in its lifecycle.
    /// </summary>
    public StayStatus Status { get; private set; }

    /// <summary>
    /// Whether the guest is currently staying, so requests can be delivered to their unit.
    /// </summary>
    public bool IsInHouse => Status == StayStatus.InHouse;

    /// <summary>
    /// Creates a reserved stay and raises <see cref="StayContextCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="guest">The guest, loaded by the caller; determines the tenant.</param>
    /// <param name="propertyId">The property of the stay.</param>
    /// <param name="arrival">Property-local arrival date.</param>
    /// <param name="departure">Property-local departure date; after arrival.</param>
    /// <param name="unitId">Assigned unit, if already known.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The stay, or a <see cref="ValidationError"/>.</returns>
    public static Result<StayContext> Create(
        StayContextId id,
        Guest guest,
        PropertyId propertyId,
        DateOnly arrival,
        DateOnly departure,
        AccommodationUnitId? unitId,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(guest);

        Error? datesError = ValidateDates(arrival, departure);

        if (datesError is not null)
        {
            return datesError;
        }

        StayContext stay = new(id, guest.TenantId, propertyId, guest.Id, arrival, departure, unitId);
        stay.RaiseCreated(now);

        return stay;
    }

    /// <summary>
    /// Marks the guest as arrived, optionally assigning the unit, and raises <see cref="StayContextUpdated"/>.
    /// Checking in an in-house stay with no new unit is a no-op.
    /// </summary>
    /// <param name="unitId">The unit, if not assigned yet or changed at check-in; <c>null</c> keeps the current one.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result CheckIn(AccommodationUnitId? unitId, DateTimeOffset now)
    {
        if (Status is StayStatus.CheckedOut or StayStatus.Cancelled)
        {
            return Error.InvalidState("stay.ended", $"A {Status} stay cannot be checked in.");
        }

        AccommodationUnitId? unit = unitId ?? AccommodationUnitId;

        if (unit is null)
        {
            return Error.InvalidState("stay.unit_required", "Assign a unit before or at check-in.");
        }

        if (Status == StayStatus.InHouse && unit == AccommodationUnitId)
        {
            return Result.Success();
        }

        Status = StayStatus.InHouse;
        AccommodationUnitId = unit;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Assigns or changes the unit (e.g. a room move) and raises <see cref="StayContextUpdated"/>.
    /// Assigning the current unit is a no-op.
    /// </summary>
    /// <param name="unitId">The unit.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error when the stay has ended.</returns>
    public Result AssignUnit(AccommodationUnitId unitId, DateTimeOffset now)
    {
        if (Status is StayStatus.CheckedOut or StayStatus.Cancelled)
        {
            return Error.InvalidState("stay.ended", $"A {Status} stay cannot change unit.");
        }

        if (unitId == AccommodationUnitId)
        {
            return Result.Success();
        }

        AccommodationUnitId = unitId;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Changes the stay dates (e.g. an extension) and raises <see cref="StayContextUpdated"/>.
    /// </summary>
    /// <param name="arrival">Property-local arrival date.</param>
    /// <param name="departure">Property-local departure date; after arrival.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, a <see cref="ValidationError"/>, or an <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result ChangeDates(DateOnly arrival, DateOnly departure, DateTimeOffset now)
    {
        if (Status is StayStatus.CheckedOut or StayStatus.Cancelled)
        {
            return Error.InvalidState("stay.ended", $"A {Status} stay cannot change dates.");
        }

        if (Status == StayStatus.InHouse && arrival != Arrival)
        {
            return Error.InvalidState("stay.arrival_fixed", "The arrival date cannot change after check-in.");
        }

        Error? datesError = ValidateDates(arrival, departure);

        if (datesError is not null)
        {
            return datesError;
        }

        if (arrival == Arrival && departure == Departure)
        {
            return Result.Success();
        }

        Arrival = arrival;
        Departure = departure;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Marks the guest as departed and raises <see cref="StayContextUpdated"/>. Checking out twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error unless in house.</returns>
    public Result CheckOut(DateTimeOffset now) => TransitionTo(StayStatus.CheckedOut, StayStatus.InHouse, now);

    /// <summary>
    /// Calls off a reserved stay and raises <see cref="StayContextUpdated"/>. Cancelling twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error unless reserved.</returns>
    public Result Cancel(DateTimeOffset now) => TransitionTo(StayStatus.Cancelled, StayStatus.Reserved, now);

    private Result TransitionTo(StayStatus target, StayStatus requiredCurrent, DateTimeOffset now)
    {
        if (Status == target)
        {
            return Result.Success();
        }

        if (Status != requiredCurrent)
        {
            return Error.InvalidState("stay.transition_invalid", $"A {Status} stay cannot become {target}.");
        }

        Status = target;
        RaiseUpdated(now);

        return Result.Success();
    }

    private static ValidationError? ValidateDates(DateOnly arrival, DateOnly departure)
    {
        if (departure <= arrival)
        {
            return Error.Validation("departure", "stay.departure_before_arrival", "Departure must be after arrival.");
        }

        if (departure.DayNumber - arrival.DayNumber > MaxNights)
        {
            return Error.Validation("departure", "stay.too_long", $"A stay may last at most {MaxNights} nights.");
        }

        return null;
    }

    private void RaiseCreated(DateTimeOffset now) =>
        Raise(new StayContextCreated(Id, PropertyId, GuestId, Arrival, Departure, AccommodationUnitId, Status, now));

    private void RaiseUpdated(DateTimeOffset now) =>
        Raise(new StayContextUpdated(Id, Arrival, Departure, AccommodationUnitId, Status, now));
}
