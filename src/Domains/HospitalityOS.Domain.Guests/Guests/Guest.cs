using HospitalityOS.Domain.Guests.Guests.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Guests.Guests;

/// <summary>
/// A person the platform serves. Stays (<see cref="StayContexts.StayContext"/>) and conversations reference
/// the guest by ID. Holds only a minimal <see cref="GuestProfile"/> (P10).
/// </summary>
public sealed class Guest : AggregateRoot<GuestId>, ITenantScoped
{
    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private Guest()
    {
        Profile = null!;
    }

    private Guest(GuestId id, TenantId tenantId, GuestProfile profile)
        : base(id)
    {
        TenantId = tenantId;
        Profile = profile;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// Validated, normalized profile.
    /// </summary>
    public GuestProfile Profile { get; private set; }

    /// <summary>
    /// Registers a guest and raises <see cref="GuestRegistered"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="profile">Profile; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The guest, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Guest> Register(GuestId id, TenantId tenantId, GuestProfile profile, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(profile);

        Result<GuestProfile> valid = Validate(profile);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Guest guest = new(id, tenantId, valid.Value);
        guest.Raise(new GuestRegistered(id, now));

        return guest;
    }

    /// <summary>
    /// Replaces the profile and raises <see cref="GuestProfileUpdated"/>. A no-change update is a no-op (P8).
    /// </summary>
    /// <param name="profile">New profile; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result UpdateProfile(GuestProfile profile, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(profile);

        Result<GuestProfile> valid = Validate(profile);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Profile)
        {
            return Result.Success();
        }

        Profile = valid.Value;
        Raise(new GuestProfileUpdated(Id, now));

        return Result.Success();
    }

    private static Result<GuestProfile> Validate(GuestProfile profile)
    {
        List<FieldError> errors = [];

        string? displayName = TextRules.Optional(profile.DisplayName, "displayName", "guest.display_name", errors, 100);
        string? language = NormalizeLanguage(profile.PreferredLanguage, errors);

        return errors.Count > 0 ? ValidationError.From(errors) : new GuestProfile(displayName, language);
    }

    // Accepts "en", "eng", "en-US", "pt-br" (normalized to "pt-BR"); a light check, not full BCP 47.
    private static string? NormalizeLanguage(string? value, List<FieldError> errors)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        string[] parts = value.Trim().Replace('_', '-').Split('-');
        bool valid = parts.Length <= 2
            && parts[0].Length is 2 or 3 && parts[0].All(char.IsAsciiLetter)
            && (parts.Length == 1 || (parts[1].Length is 2 && parts[1].All(char.IsAsciiLetter)));

        if (!valid)
        {
            errors.Add(new FieldError("preferredLanguage", "guest.preferred_language_invalid", "Preferred language must be a tag such as 'en' or 'pt-BR'."));
            return null;
        }

        return parts.Length == 1
            ? parts[0].ToLowerInvariant()
            : $"{parts[0].ToLowerInvariant()}-{parts[1].ToUpperInvariant()}";
    }
}
