using HospitalityOS.Domain.Capabilities.AITraces.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Execution;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Capabilities.AITraces;

/// <summary>
/// The record of one AI turn (spec §26, P11): what triggered it, who acted, how it ended, and, in <see cref="Body"/>, the
/// full account of what the agent read, which models it called with which prompts, every capability call, and what it
/// answered. Immutable once recorded, so a trace stays tied to the data versions it used (spec §27).
/// </summary>
/// <remarks>
/// The body is kept whole, including guest text; sensitive data is redacted when a trace is read, according to the
/// reader's role. Values come from the AI layer's recorder, so invalid values here are programming errors and throw.
/// </remarks>
public sealed class AITrace : AggregateRoot<AITraceId>, ITenantScoped
{
    /// <summary>
    /// Maximum length of <see cref="TriggerType"/>.
    /// </summary>
    public const int MaxTriggerTypeLength = 100;

    /// <summary>
    /// Maximum length of <see cref="Intent"/>.
    /// </summary>
    public const int MaxIntentLength = 100;

    /// <summary>
    /// Maximum length of <see cref="ActorId"/>.
    /// </summary>
    public const int MaxActorIdLength = 200;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private AITrace()
    {
        TriggerType = null!;
        Body = null!;
    }

    private AITrace(
        AITraceId id,
        TenantId tenantId,
        PropertyId? propertyId,
        Actor actor,
        Guid correlationId,
        Guid? causationId,
        string triggerType,
        Guid? triggerId,
        string? intent,
        AITraceOutcome outcome,
        DateTimeOffset startedAt,
        DateTimeOffset completedAt,
        string body)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        ActorType = actor.Type;
        ActorId = actor.Id;
        CorrelationId = correlationId;
        CausationId = causationId;
        TriggerType = triggerType;
        TriggerId = triggerId;
        Intent = intent;
        Outcome = outcome;
        StartedAt = startedAt;
        CompletedAt = completedAt;
        Body = body;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the turn concerned, if any.
    /// </summary>
    public PropertyId? PropertyId { get; }

    /// <summary>
    /// The kind of actor that ran the turn, usually <see cref="ActorType.Agent"/>.
    /// </summary>
    public ActorType ActorType { get; }

    /// <summary>
    /// The actor's identifier, e.g. the agent's name.
    /// </summary>
    public string? ActorId { get; }

    /// <summary>
    /// The flow the turn ran in (P11).
    /// </summary>
    public Guid CorrelationId { get; }

    /// <summary>
    /// The event or message that directly caused the turn, if any.
    /// </summary>
    public Guid? CausationId { get; }

    /// <summary>
    /// What kind of thing triggered the turn, e.g. <c>GuestMessage</c> or an event type.
    /// </summary>
    public string TriggerType { get; }

    /// <summary>
    /// The message or event that triggered it, if it has an ID.
    /// </summary>
    public Guid? TriggerId { get; }

    /// <summary>
    /// What the agent understood was being asked for, e.g. <c>question</c>, if it decided.
    /// </summary>
    public string? Intent { get; }

    /// <summary>
    /// How the turn ended.
    /// </summary>
    public AITraceOutcome Outcome { get; }

    /// <summary>
    /// When the turn's first recorded step began (UTC).
    /// </summary>
    public DateTimeOffset StartedAt { get; }

    /// <summary>
    /// When the turn was completed (UTC).
    /// </summary>
    public DateTimeOffset CompletedAt { get; }

    /// <summary>
    /// The full account of the turn as JSON in the wire format, unredacted.
    /// </summary>
    public string Body { get; }

    /// <summary>
    /// The actor that ran the turn.
    /// </summary>
    public Actor Actor => new(ActorType, ActorId);

    /// <summary>
    /// Records a completed AI turn. Raises <see cref="AITraceCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The tenant the turn ran for.</param>
    /// <param name="propertyId">The property it concerned, if any.</param>
    /// <param name="actor">Who ran it.</param>
    /// <param name="correlationId">The flow.</param>
    /// <param name="causationId">The cause, if any.</param>
    /// <param name="triggerType">What kind of thing triggered it; trimmed, at most <see cref="MaxTriggerTypeLength"/> characters.</param>
    /// <param name="triggerId">The trigger's ID, if it has one.</param>
    /// <param name="intent">The interpreted intent, if any; trimmed, at most <see cref="MaxIntentLength"/> characters.</param>
    /// <param name="outcome">How it ended.</param>
    /// <param name="startedAt">When it began.</param>
    /// <param name="completedAt">When it was completed; not before <paramref name="startedAt"/>.</param>
    /// <param name="body">The full account as JSON; not empty.</param>
    public static AITrace Record(
        AITraceId id,
        TenantId tenantId,
        PropertyId? propertyId,
        Actor actor,
        Guid correlationId,
        Guid? causationId,
        string triggerType,
        Guid? triggerId,
        string? intent,
        AITraceOutcome outcome,
        DateTimeOffset startedAt,
        DateTimeOffset completedAt,
        string body)
    {
        ArgumentNullException.ThrowIfNull(actor);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(actor.Id?.Length ?? 0, MaxActorIdLength, nameof(actor));
        EnsureTrimmed(triggerType, MaxTriggerTypeLength, nameof(triggerType));

        if (intent is not null)
        {
            EnsureTrimmed(intent, MaxIntentLength, nameof(intent));
        }

        if (!Enum.IsDefined(outcome))
        {
            throw new ArgumentOutOfRangeException(nameof(outcome), outcome, "Unknown trace outcome.");
        }

        ArgumentOutOfRangeException.ThrowIfLessThan(completedAt, startedAt);
        ArgumentException.ThrowIfNullOrWhiteSpace(body);

        AITrace trace = new(id, tenantId, propertyId, actor, correlationId, causationId, triggerType, triggerId, intent, outcome, startedAt, completedAt, body);
        trace.Raise(new AITraceCreated(id, propertyId, actor.Id, triggerType, triggerId, outcome, completedAt));

        return trace;
    }

    private static void EnsureTrimmed(string value, int maxLength, string name)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(value, name);
        ArgumentOutOfRangeException.ThrowIfGreaterThan(value.Length, maxLength, name);

        if (value != value.Trim())
        {
            throw new ArgumentException("The value must be trimmed.", name);
        }
    }
}
