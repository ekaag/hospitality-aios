using HospitalityOS.Domain.Organizations.Access.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Execution;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Organizations.Access;

/// <summary>
/// Someone's access to a tenant (K4b): their role, for workers the roster entry they work as, and how they sign in. An
/// administrator invites them with a one-time code; signing in with the identity provider and redeeming the code links
/// their sign-in, after which every token they bring acts as them. The identity provider proves who someone is; this
/// decides what they may do, so revoking it takes effect on their next request.
/// </summary>
/// <remarks>
/// Only the code's hash is kept, and events carry neither it nor the sign-in.
/// </remarks>
public sealed class StaffAccess : AggregateRoot<StaffAccessId>, ITenantScoped
{
    /// <summary>
    /// Maximum length of <see cref="DisplayName"/>.
    /// </summary>
    public const int MaxDisplayNameLength = TextRules.MaxTextLength;

    /// <summary>
    /// Maximum length of <see cref="SignInIssuer"/>.
    /// </summary>
    public const int MaxIssuerLength = 400;

    /// <summary>
    /// Maximum length of <see cref="SignInSubject"/>.
    /// </summary>
    public const int MaxSubjectLength = 200;

    /// <summary>
    /// Length of <see cref="InviteCodeHash"/>: a SHA-256 hash in lowercase hex.
    /// </summary>
    public const int InviteCodeHashLength = 64;

    /// <summary>
    /// Longest an invite may stay open.
    /// </summary>
    public static TimeSpan MaxInviteLifetime { get; } = TimeSpan.FromDays(30);

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private StaffAccess()
    {
        DisplayName = null!;
    }

    private StaffAccess(StaffAccessId id, TenantId tenantId, string displayName, StaffRole role, StaffMemberId? staffMemberId)
        : base(id)
    {
        TenantId = tenantId;
        DisplayName = displayName;
        Role = role;
        StaffMemberId = staffMemberId;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// Who the access is for, as administrators know them; trimmed.
    /// </summary>
    public string DisplayName { get; private set; }

    /// <summary>
    /// What they may do.
    /// </summary>
    public StaffRole Role { get; private set; }

    /// <summary>
    /// The roster entry they work as; required for workers, whose work is routed by it.
    /// </summary>
    public StaffMemberId? StaffMemberId { get; private set; }

    /// <summary>
    /// The open invite's code hash, or <c>null</c> when no invite is open.
    /// </summary>
    public string? InviteCodeHash { get; private set; }

    /// <summary>
    /// When the open invite stops working.
    /// </summary>
    public DateTimeOffset? InviteExpiresAt { get; private set; }

    /// <summary>
    /// The identity provider that signs them in (a token's <c>iss</c>), once linked.
    /// </summary>
    public string? SignInIssuer { get; private set; }

    /// <summary>
    /// Who they are to <see cref="SignInIssuer"/> (its stable user ID), once linked.
    /// </summary>
    public string? SignInSubject { get; private set; }

    /// <summary>
    /// When their sign-in was linked.
    /// </summary>
    public DateTimeOffset? LinkedAt { get; private set; }

    /// <summary>
    /// When the access was revoked, after which it opens nothing.
    /// </summary>
    public DateTimeOffset? RevokedAt { get; private set; }

    /// <summary>
    /// Where the access stands.
    /// </summary>
    public StaffAccessStatus Status =>
        RevokedAt is not null ? StaffAccessStatus.Revoked
        : SignInSubject is not null ? StaffAccessStatus.Active
        : StaffAccessStatus.Invited;

    /// <summary>
    /// Gives someone access, invited with a code, and raises <see cref="StaffAccessGranted"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The tenant they get access to.</param>
    /// <param name="displayName">Who they are; required.</param>
    /// <param name="role">What they may do.</param>
    /// <param name="staffMemberId">Their roster entry; required for workers.</param>
    /// <param name="invite">The invite's code hash and expiry.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The access, or a <see cref="ValidationError"/> listing every problem.</returns>
    public static Result<StaffAccess> Create(
        StaffAccessId id, TenantId tenantId, string displayName, StaffRole role, StaffMemberId? staffMemberId, StaffInvite invite, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(invite);
        List<FieldError> errors = [];
        string name = TextRules.Required(displayName, "displayName", "access.display_name", errors, MaxDisplayNameLength);

        if (!Enum.IsDefined(role))
        {
            errors.Add(new FieldError("role", "access.role_invalid", $"Role must be one of {string.Join(", ", Enum.GetNames<StaffRole>())}."));
        }
        else if (role == StaffRole.Worker && staffMemberId is null)
        {
            errors.Add(new FieldError("staffMemberId", "access.staff_member_required", "A worker's access names the roster entry they work as."));
        }

        ValidateInvite(invite, now, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        StaffAccess access = new(id, tenantId, name, role, staffMemberId);
        access.Open(invite);
        access.Raise(new StaffAccessGranted(id, role, staffMemberId, now));
        return access;
    }

    /// <summary>
    /// Links the sign-in of whoever brings the open invite's code, closing the invite, and raises
    /// <see cref="StaffAccessLinked"/>.
    /// </summary>
    /// <param name="inviteCodeHash">The hash of the code they brought.</param>
    /// <param name="issuer">Their token's issuer.</param>
    /// <param name="subject">Their stable user ID at the issuer.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success; <c>access.invite_not_found</c> when no open invite has the code; <c>access.invite_expired</c>;
    /// <c>access.revoked</c>; or a <see cref="ValidationError"/> for a sign-in without an issuer or subject.</returns>
    public Result Redeem(string inviteCodeHash, string issuer, string subject, DateTimeOffset now)
    {
        if (RevokedAt is not null)
        {
            return Revoked;
        }

        if (InviteCodeHash is null || !string.Equals(InviteCodeHash, inviteCodeHash, StringComparison.Ordinal))
        {
            return Error.NotFound("access.invite_not_found", "No open invite has this code.");
        }

        if (now >= InviteExpiresAt)
        {
            return Error.InvalidState("access.invite_expired", "This invite has expired; ask an administrator for a new one.");
        }

        List<FieldError> errors = [];
        string validIssuer = TextRules.Required(issuer, "issuer", "access.issuer", errors, MaxIssuerLength);
        string validSubject = TextRules.Required(subject, "subject", "access.subject", errors, MaxSubjectLength);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        SignInIssuer = validIssuer;
        SignInSubject = validSubject;
        LinkedAt = now;
        InviteCodeHash = null;
        InviteExpiresAt = null;
        Raise(new StaffAccessLinked(Id, now));
        return Result.Success();
    }

    /// <summary>
    /// Opens a new invite in place of any open one and unlinks the current sign-in, so whoever redeems it signs in from
    /// then on (a lost account, or a code that expired unused); raises <see cref="StaffAccessReinvited"/>.
    /// </summary>
    /// <returns>Success; <c>access.revoked</c>; or a <see cref="ValidationError"/>.</returns>
    public Result Reinvite(StaffInvite invite, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(invite);

        if (RevokedAt is not null)
        {
            return Revoked;
        }

        List<FieldError> errors = [];
        ValidateInvite(invite, now, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        SignInIssuer = null;
        SignInSubject = null;
        LinkedAt = null;
        Open(invite);
        Raise(new StaffAccessReinvited(Id, now));
        return Result.Success();
    }

    /// <summary>
    /// Ends the access, so its sign-in and any open invite stop working, and raises <see cref="StaffAccessRevoked"/>.
    /// Revoking it again is a successful no-op raising nothing (P8).
    /// </summary>
    public Result Revoke(DateTimeOffset now)
    {
        if (RevokedAt is not null)
        {
            return Result.Success();
        }

        RevokedAt = now;
        InviteCodeHash = null;
        InviteExpiresAt = null;

        // Unlinked, so the same person can be given new access later.
        SignInIssuer = null;
        SignInSubject = null;
        Raise(new StaffAccessRevoked(Id, now));
        return Result.Success();
    }

    private static Error Revoked => Error.InvalidState("access.revoked", "This access has been revoked.");

    private void Open(StaffInvite invite)
    {
        InviteCodeHash = invite.CodeHash;
        InviteExpiresAt = invite.ExpiresAt;
    }

    private static void ValidateInvite(StaffInvite invite, DateTimeOffset now, List<FieldError> errors)
    {
        if (invite.CodeHash is not { Length: InviteCodeHashLength } hash || !hash.All(c => char.IsAsciiDigit(c) || c is >= 'a' and <= 'f'))
        {
            errors.Add(new FieldError("invite", "access.invite_hash_invalid", $"An invite's code hash is {InviteCodeHashLength} lowercase hex digits."));
        }

        if (invite.ExpiresAt <= now || invite.ExpiresAt > now + MaxInviteLifetime)
        {
            errors.Add(new FieldError("inviteExpiresAt", "access.invite_expiry_invalid", $"An invite expires after now and within {MaxInviteLifetime.TotalDays} days."));
        }
    }
}

/// <summary>
/// A one-time invite: the hash of its code and when it stops working.
/// </summary>
public sealed record StaffInvite(string CodeHash, DateTimeOffset ExpiresAt);

/// <summary>
/// Where someone's access stands.
/// </summary>
public enum StaffAccessStatus
{
    /// <summary>
    /// Invited; no sign-in linked yet.
    /// </summary>
    Invited,

    /// <summary>
    /// A sign-in is linked and acts as them.
    /// </summary>
    Active,

    /// <summary>
    /// Revoked; opens nothing.
    /// </summary>
    Revoked,
}
