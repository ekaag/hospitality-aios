using HospitalityOS.Domain.Organizations.Organizations.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Organizations.Organizations;

/// <summary>
/// A company that owns or operates properties. Belongs to one tenant; its properties reference it by ID.
/// </summary>
public sealed class Organization : AggregateRoot<OrganizationId>, ITenantScoped
{
    /// <summary>
    /// Maximum length of <see cref="Name"/>.
    /// </summary>
    public const int MaxNameLength = 200;

    private Organization(OrganizationId id, TenantId tenantId, string name)
        : base(id)
    {
        TenantId = tenantId;
        Name = name;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// Display name, trimmed.
    /// </summary>
    public string Name { get; private set; }

    /// <summary>
    /// Creates an organization and raises <see cref="OrganizationCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="name">Display name; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The organization, or a <see cref="ValidationError"/>.</returns>
    public static Result<Organization> Create(OrganizationId id, TenantId tenantId, string name, DateTimeOffset now)
    {
        Result<string> validName = ValidateName(name);

        if (validName.IsFailure)
        {
            return validName.Error;
        }

        Organization organization = new(id, tenantId, validName.Value);
        organization.Raise(new OrganizationCreated(id, organization.Name, now));

        return organization;
    }

    /// <summary>
    /// Renames the organization and raises <see cref="OrganizationUpdated"/>. Renaming to the current name
    /// is a successful no-op that raises nothing, so retried requests are harmless (P8).
    /// </summary>
    /// <param name="name">New display name; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/>.</returns>
    public Result Rename(string name, DateTimeOffset now)
    {
        Result<string> validName = ValidateName(name);

        if (validName.IsFailure)
        {
            return validName.Error;
        }

        if (validName.Value == Name)
        {
            return Result.Success();
        }

        Name = validName.Value;
        Raise(new OrganizationUpdated(Id, Name, now));

        return Result.Success();
    }

    private static Result<string> ValidateName(string? name)
    {
        string trimmed = name?.Trim() ?? "";

        if (trimmed.Length == 0)
        {
            return Error.Validation("name", "organization.name_required", "Name is required.");
        }

        if (trimmed.Length > MaxNameLength)
        {
            return Error.Validation("name", "organization.name_too_long", $"Name must be at most {MaxNameLength} characters.");
        }

        return trimmed;
    }
}
