using HospitalityOS.Domain.Services.ServiceRequests.Events;
using HospitalityOS.Domain.Services.Services;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Locations;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Services.ServiceRequests;

/// <summary>
/// A guest's canonical request for a service, e.g. two bath towels to Room 412 (Journey 9). Physical work is
/// done through Operations' <c>HumanAction</c>s; their events move the request through its statuses without
/// any manager action (P2).
/// </summary>
/// <remarks>
/// Lifecycle: Open → InProgress → Completed, with Exception for failed/unresolved work (still open, Journey 20)
/// and Cancelled. Completing a completed request is a no-op, so duplicate <c>HumanActionCompleted</c>
/// delivery completes it once logically (Journey 19, P8).
/// </remarks>
public sealed class ServiceRequest : AggregateRoot<ServiceRequestId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Maximum length of <see cref="ServiceRequestDetails.Description"/>.
    /// </summary>
    public const int MaxDescriptionLength = 1000;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private ServiceRequest()
    {
        Details = null!;
        Origin = null!;
    }

    private ServiceRequest(
        ServiceRequestId id,
        Service service,
        ServiceRequestDetails details,
        RequestOrigin origin,
        DateTimeOffset createdAt)
        : base(id)
    {
        TenantId = service.TenantId;
        PropertyId = service.PropertyId;
        ServiceId = service.Id;
        ServiceCategory = service.Details.Category;
        Details = details;
        Origin = origin;
        CreatedAt = createdAt;
        DueAt = service.Details.TargetCompletion is { } target ? createdAt + target : null;
        Status = ServiceRequestStatus.Open;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property fulfilling the request.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The requested service.
    /// </summary>
    public ServiceId ServiceId { get; }

    /// <summary>
    /// The service's category at request time (e.g. Maintenance), used to route the work.
    /// </summary>
    public ServiceCategory ServiceCategory { get; }

    /// <summary>
    /// Validated, normalized request details.
    /// </summary>
    public ServiceRequestDetails Details { get; }

    /// <summary>
    /// Who and what the request came from.
    /// </summary>
    public RequestOrigin Origin { get; }

    /// <summary>
    /// When the request was created (UTC).
    /// </summary>
    public DateTimeOffset CreatedAt { get; }

    /// <summary>
    /// Target completion time from the service's target, if it has one. Not an ETA to quote to guests (Journey 12).
    /// </summary>
    public DateTimeOffset? DueAt { get; }

    /// <summary>
    /// Canonical status.
    /// </summary>
    public ServiceRequestStatus Status { get; private set; }

    /// <summary>
    /// Why the request is in <see cref="ServiceRequestStatus.Exception"/>, if it is or was.
    /// </summary>
    public string? ExceptionReason { get; private set; }

    /// <summary>
    /// When the request was completed (UTC).
    /// </summary>
    public DateTimeOffset? CompletedAt { get; private set; }

    /// <summary>
    /// Whether the request is still unresolved (open, in progress, or in exception).
    /// </summary>
    public bool IsActive => Status is ServiceRequestStatus.Open or ServiceRequestStatus.InProgress or ServiceRequestStatus.Exception;

    /// <summary>
    /// Creates an open request for a service and raises <see cref="ServiceRequestCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="service">The requested service, loaded by the caller; determines tenant and property.</param>
    /// <param name="details">What is requested; validated against the service.</param>
    /// <param name="origin">Who and what it came from.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The request, or a <see cref="ValidationError"/> listing every problem.</returns>
    public static Result<ServiceRequest> Create(
        ServiceRequestId id,
        Service service,
        ServiceRequestDetails details,
        RequestOrigin origin,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(service);
        ArgumentNullException.ThrowIfNull(details);
        ArgumentNullException.ThrowIfNull(origin);

        Result<ServiceRequestDetails> valid = Validate(service, details, origin);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        ServiceRequest request = new(id, service, valid.Value, origin, now);
        request.Raise(new ServiceRequestCreated(
            id, request.PropertyId, request.ServiceId, request.ServiceCategory, request.Details, request.Origin, request.DueAt, now));

        return request;
    }

    /// <summary>
    /// Records that work has started (e.g. on <c>HumanActionStarted</c>) and raises <see cref="ServiceRequestUpdated"/>.
    /// A no-op when already in progress; also leaves an exception once work restarts.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error when final.</returns>
    public Result MarkInProgress(DateTimeOffset now)
    {
        if (Status == ServiceRequestStatus.InProgress)
        {
            return Result.Success();
        }

        if (!IsActive)
        {
            return FinalError("started");
        }

        Status = ServiceRequestStatus.InProgress;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Records that work failed or stalled, keeping the request unresolved (Journey 20), and raises
    /// <see cref="ServiceRequestUpdated"/>. Recording the same reason again is a no-op.
    /// </summary>
    /// <param name="reason">What went wrong, e.g. "Worker could not access the room"; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, a <see cref="ValidationError"/>, or an <see cref="ErrorKind.InvalidState"/> error when final.</returns>
    public Result RecordException(string reason, DateTimeOffset now)
    {
        List<FieldError> errors = [];
        string trimmed = TextRules.Required(reason, "reason", "service_request.exception_reason", errors, MaxDescriptionLength);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        if (!IsActive)
        {
            return FinalError("put into exception");
        }

        if (Status == ServiceRequestStatus.Exception && ExceptionReason == trimmed)
        {
            return Result.Success();
        }

        Status = ServiceRequestStatus.Exception;
        ExceptionReason = trimmed;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Completes the request (e.g. on <c>HumanActionCompleted</c>) and raises <see cref="ServiceRequestCompleted"/>.
    /// Completing again is a no-op that raises nothing, so the guest is notified once (Journey 19).
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error when cancelled.</returns>
    public Result Complete(DateTimeOffset now)
    {
        if (Status == ServiceRequestStatus.Completed)
        {
            return Result.Success();
        }

        if (!IsActive)
        {
            return FinalError("completed");
        }

        Status = ServiceRequestStatus.Completed;
        CompletedAt = now;
        Raise(new ServiceRequestCompleted(Id, PropertyId, Origin, now));

        return Result.Success();
    }

    /// <summary>
    /// Withdraws the request and raises <see cref="ServiceRequestUpdated"/>. Cancelling twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error when completed.</returns>
    public Result Cancel(DateTimeOffset now)
    {
        if (Status == ServiceRequestStatus.Cancelled)
        {
            return Result.Success();
        }

        if (!IsActive)
        {
            return FinalError("cancelled");
        }

        Status = ServiceRequestStatus.Cancelled;
        RaiseUpdated(now);

        return Result.Success();
    }

    private Error FinalError(string action) =>
        Error.InvalidState("service_request.final", $"A {Status} request cannot be {action}.");

    private void RaiseUpdated(DateTimeOffset now) => Raise(new ServiceRequestUpdated(Id, Status, ExceptionReason, now));

    private static Result<ServiceRequestDetails> Validate(Service service, ServiceRequestDetails details, RequestOrigin origin)
    {
        List<FieldError> errors = [];

        if (origin.IsGuestInitiated && !service.Details.IsGuestRequestable)
        {
            errors.Add(new FieldError("serviceId", "service_request.service_not_requestable", "Guests cannot request this service."));
        }

        ActionLocation? location = LocationRules.Validate(details.Location, "location", "service_request.location", errors);
        string? description = TextRules.Optional(details.Description, "description", "service_request.description", errors, MaxDescriptionLength);
        string? itemCode = ValidateItem(service, details, description, errors);

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Location = location!, ItemCode = itemCode, Description = description };
    }

    private static string? ValidateItem(Service service, ServiceRequestDetails details, string? description, List<FieldError> errors)
    {
        bool hasItems = service.Details.Items!.Count > 0;

        if (string.IsNullOrWhiteSpace(details.ItemCode))
        {
            if (hasItems)
            {
                errors.Add(new FieldError("itemCode", "service_request.item_required", $"Choose one of: {string.Join(", ", service.Details.Items!.Select(item => item.Code))}."));
            }
            else if (description is null)
            {
                errors.Add(new FieldError("description", "service_request.description_required", "Describe what is needed."));
            }

            if (details.Quantity != 1)
            {
                errors.Add(new FieldError("quantity", "service_request.quantity_out_of_range", "Quantity must be 1 when no item is requested."));
            }

            return null;
        }

        ServiceItem? item = service.FindItem(details.ItemCode);

        if (item is null)
        {
            errors.Add(new FieldError("itemCode", "service_request.item_unknown", $"'{details.ItemCode.Trim()}' is not an item of this service."));
            return details.ItemCode.Trim();
        }

        if (details.Quantity < 1 || details.Quantity > item.MaxQuantityPerRequest)
        {
            errors.Add(new FieldError("quantity", "service_request.quantity_out_of_range", $"Quantity must be between 1 and {item.MaxQuantityPerRequest} for {item.Name}."));
        }

        return item.Code;
    }
}
