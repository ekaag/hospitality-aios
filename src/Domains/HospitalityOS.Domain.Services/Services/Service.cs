using HospitalityOS.Domain.Services.Services.Events;
using HospitalityOS.SharedKernel.Collections;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Services.Services;

/// <summary>
/// Something the property does for guests, e.g. delivering towels or fixing the AC. Guest service requests
/// (B9) reference a service and, optionally, one of its items.
/// </summary>
/// <remarks>
/// Codes must be unique within a property. That spans aggregates, so the application layer checks it through
/// <see cref="IServiceRepository.FindByCodeAsync"/> and persistence backs it with a unique index.
/// </remarks>
public sealed class Service : AggregateRoot<ServiceId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Maximum number of items per service.
    /// </summary>
    public const int MaxItems = 50;

    /// <summary>
    /// Upper bound for <see cref="ServiceItem.MaxQuantityPerRequest"/>.
    /// </summary>
    public const int MaxQuantityLimit = 100;

    /// <summary>
    /// Longest allowed <see cref="ServiceDetails.TargetCompletion"/>.
    /// </summary>
    public static TimeSpan MaxTargetCompletion { get; } = TimeSpan.FromDays(7);

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private Service()
    {
        Details = null!;
    }

    private Service(ServiceId id, TenantId tenantId, PropertyId propertyId, ServiceDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property offering the service.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized definition. <see cref="ServiceDetails.Items"/> is never <c>null</c> here.
    /// </summary>
    public ServiceDetails Details { get; private set; }

    /// <summary>
    /// Creates a service and raises <see cref="ServiceCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property offering the service.</param>
    /// <param name="details">Definition; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The service, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Service> Create(ServiceId id, TenantId tenantId, PropertyId propertyId, ServiceDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<ServiceDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Service service = new(id, tenantId, propertyId, valid.Value);
        service.Raise(new ServiceCreated(id, propertyId, service.Details, now));

        return service;
    }

    /// <summary>
    /// Replaces the definition and raises <see cref="ServiceUpdated"/>. A no-change update is a successful no-op (P8).
    /// </summary>
    /// <param name="details">New definition; validated and normalized. The caller checks code uniqueness.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(ServiceDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<ServiceDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        Raise(new ServiceUpdated(Id, Details, now));

        return Result.Success();
    }

    /// <summary>
    /// Finds a requestable item by code (case-insensitive), or returns <c>null</c>.
    /// </summary>
    /// <param name="itemCode">The item code, e.g. <c>bath_towel</c>.</param>
    public ServiceItem? FindItem(string itemCode) =>
        Details.Items!.FirstOrDefault(item => string.Equals(item.Code, itemCode?.Trim(), StringComparison.OrdinalIgnoreCase));

    private static Result<ServiceDetails> Validate(ServiceDetails details)
    {
        List<FieldError> errors = [];

        string code = TextRules.Code(details.Code, "code", "service.code", errors);
        string name = TextRules.Required(details.Name, "name", "service.name", errors);
        string? description = TextRules.Optional(details.Description, "description", "service.description", errors, TextRules.MaxLongTextLength);
        ValueList<ServiceItem> items = ValidateItems(details.Items ?? [], errors);

        if (!Enum.IsDefined(details.Category))
        {
            errors.Add(new FieldError("category", "service.category_invalid", $"'{details.Category}' is not a known service category."));
        }

        if (details.TargetCompletion is { } target && (target <= TimeSpan.Zero || target > MaxTargetCompletion))
        {
            errors.Add(new FieldError("targetCompletion", "service.target_completion_out_of_range", $"Target completion must be positive and at most {MaxTargetCompletion.TotalDays} days."));
        }

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Code = code, Name = name, Description = description, Items = items };
    }

    private static ValueList<ServiceItem> ValidateItems(ValueList<ServiceItem> items, List<FieldError> errors)
    {
        if (items.Count > MaxItems)
        {
            errors.Add(new FieldError("items", "service.too_many_items", $"At most {MaxItems} items are allowed."));
        }

        HashSet<string> codes = [];
        List<ServiceItem> normalized = [];

        for (int i = 0; i < items.Count; i++)
        {
            string path = $"items[{i}]";
            ServiceItem? item = items[i];

            if (item is null)
            {
                errors.Add(new FieldError(path, "service.item_required", $"{path} is required."));
                continue;
            }

            int errorCount = errors.Count;
            string code = TextRules.Code(item.Code, path + ".code", "service.item_code", errors);

            // Duplicates depend only on the code itself, not on the item's other fields.
            if (errors.Count == errorCount && !codes.Add(code))
            {
                errors.Add(new FieldError(path + ".code", "service.item_code_duplicate", $"Item code '{code}' appears more than once."));
            }

            string name = TextRules.Required(item.Name, path + ".name", "service.item_name", errors);

            if (item.MaxQuantityPerRequest is < 1 or > MaxQuantityLimit)
            {
                errors.Add(new FieldError(path + ".maxQuantityPerRequest", "service.item_max_quantity_out_of_range", $"Max quantity must be between 1 and {MaxQuantityLimit}."));
            }

            normalized.Add(new ServiceItem(code, name, item.MaxQuantityPerRequest));
        }

        return ValueList.From(normalized);
    }
}
