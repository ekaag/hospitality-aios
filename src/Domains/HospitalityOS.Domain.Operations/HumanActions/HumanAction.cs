using HospitalityOS.Domain.Operations.HumanActions.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Operations.HumanActions;

/// <summary>
/// Physical-world work the AI cannot do itself (spec §7, P2), e.g. delivering towels to Room 412. Its
/// completion or failure re-enters the system as an event that resumes the parent workflow without a manager.
/// </summary>
/// <remarks>
/// Every transition is explicit (see <see cref="HumanActionStatus"/>); illegal ones return an
/// <see cref="ErrorKind.InvalidState"/> error. Only the current assignee may accept, start, complete, or fail.
/// Repeating a transition that already happened is a successful no-op raising nothing, so duplicate taps and
/// retried commands complete the work exactly once (Journey 14, P8).
/// </remarks>
public sealed class HumanAction : AggregateRoot<HumanActionId>, ITenantScoped, IPropertyScoped
{
    private readonly List<TaskAssignment> assignments = [];

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private HumanAction()
    {
        Details = null!;
    }

    private HumanAction(HumanActionId id, TenantId tenantId, PropertyId propertyId, HumanActionRequest details, DateTimeOffset? deadline, DateTimeOffset createdAt)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
        Deadline = deadline;
        CreatedAt = createdAt;
        Status = HumanActionStatus.Requested;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property where the work happens.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The validated, normalized request: type, instructions, location, reason, priority, SLA, items, skills,
    /// requesting agent, source event, and parent service request.
    /// </summary>
    public HumanActionRequest Details { get; }

    /// <summary>
    /// When the work must be done by (UTC): the explicit deadline, or creation time plus the SLA.
    /// </summary>
    public DateTimeOffset? Deadline { get; }

    /// <summary>
    /// Current state.
    /// </summary>
    public HumanActionStatus Status { get; private set; }

    /// <summary>
    /// Assignment history, oldest first; the last entry is the current assignee.
    /// </summary>
    public IReadOnlyList<TaskAssignment> Assignments => assignments;

    /// <summary>
    /// The current assignee, if any.
    /// </summary>
    public StaffMemberId? AssignedTo => assignments.Count == 0 ? null : assignments[^1].StaffMemberId;

    /// <summary>
    /// When the action was requested (UTC).
    /// </summary>
    public DateTimeOffset CreatedAt { get; }

    /// <summary>
    /// When the assignee accepted (UTC).
    /// </summary>
    public DateTimeOffset? AcceptedAt { get; private set; }

    /// <summary>
    /// When the assignee started (UTC); set at completion if they completed without starting.
    /// </summary>
    public DateTimeOffset? StartedAt { get; private set; }

    /// <summary>
    /// How the work was completed, once completed.
    /// </summary>
    public HumanActionCompletion? Completion { get; private set; }

    /// <summary>
    /// Why the work failed or was cancelled, if it did.
    /// </summary>
    public string? FailureReason { get; private set; }

    /// <summary>
    /// When the action reached a final state other than completion (UTC).
    /// </summary>
    public DateTimeOffset? EndedAt { get; private set; }

    /// <summary>
    /// Whether the action is in a final state.
    /// </summary>
    public bool IsFinal => Status is HumanActionStatus.Completed or HumanActionStatus.Failed or HumanActionStatus.Cancelled or HumanActionStatus.Expired;

    /// <summary>
    /// Requests physical work and raises <see cref="HumanActionRequested"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property where the work happens.</param>
    /// <param name="request">The work; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The human action, or a <see cref="ValidationError"/> listing every problem.</returns>
    public static Result<HumanAction> Request(HumanActionId id, TenantId tenantId, PropertyId propertyId, HumanActionRequest request, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(request);

        Result<HumanActionRequest> valid = HumanActionRequestRules.Validate(request, now);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        DateTimeOffset? deadline = valid.Value.Deadline ?? (valid.Value.Sla is { } sla ? now + sla : null);
        HumanAction action = new(id, tenantId, propertyId, valid.Value, deadline, now);

        action.Raise(new HumanActionRequested(
            id,
            propertyId,
            action.Details.ServiceRequestId,
            action.Details.ActionType,
            action.Details.Priority,
            action.Details.Location,
            deadline,
            action.Details.SkillsRequired!,
            now));

        return action;
    }

    /// <summary>
    /// Assigns or reassigns the work and raises <see cref="HumanActionAssigned"/>. Assigning the current assignee
    /// again is a no-op. Allowed while Requested or Assigned (before acceptance).
    /// </summary>
    /// <param name="staffMemberId">Who should do the work.</param>
    /// <param name="assignedBy">Who decided, e.g. <c>HumanActionRouter</c>; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a validation or <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Assign(StaffMemberId staffMemberId, string assignedBy, DateTimeOffset now)
    {
        if (string.IsNullOrWhiteSpace(assignedBy))
        {
            return Error.Validation("assignedBy", "human_action.assigned_by_required", "assignedBy is required.");
        }

        if (Status == HumanActionStatus.Assigned && AssignedTo == staffMemberId)
        {
            return Result.Success();
        }

        if (Status is not (HumanActionStatus.Requested or HumanActionStatus.Assigned))
        {
            return TransitionError("assigned");
        }

        assignments.Add(new TaskAssignment(staffMemberId, assignedBy.Trim(), now));
        Status = HumanActionStatus.Assigned;
        Raise(new HumanActionAssigned(Id, staffMemberId, assignedBy.Trim(), now));

        return Result.Success();
    }

    /// <summary>
    /// The assignee accepts the work and <see cref="HumanActionAccepted"/> is raised. Accepting again is a no-op.
    /// </summary>
    /// <param name="staffMemberId">Who is accepting; must be the assignee.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Accept(StaffMemberId staffMemberId, DateTimeOffset now)
    {
        if (AssignedTo != staffMemberId)
        {
            return NotAssigneeError();
        }

        if (Status == HumanActionStatus.Accepted)
        {
            return Result.Success();
        }

        if (Status != HumanActionStatus.Assigned)
        {
            return TransitionError("accepted");
        }

        Status = HumanActionStatus.Accepted;
        AcceptedAt = now;
        Raise(new HumanActionAccepted(Id, staffMemberId, now));

        return Result.Success();
    }

    /// <summary>
    /// The assignee starts the work and <see cref="HumanActionStarted"/> is raised. Starting again is a no-op.
    /// </summary>
    /// <param name="staffMemberId">Who is starting; must be the assignee.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Start(StaffMemberId staffMemberId, DateTimeOffset now)
    {
        if (AssignedTo != staffMemberId)
        {
            return NotAssigneeError();
        }

        if (Status == HumanActionStatus.InProgress)
        {
            return Result.Success();
        }

        if (Status != HumanActionStatus.Accepted)
        {
            return TransitionError("started");
        }

        Status = HumanActionStatus.InProgress;
        StartedAt = now;
        Raise(new HumanActionStarted(Id, staffMemberId, Details.ServiceRequestId, now));

        return Result.Success();
    }

    /// <summary>
    /// The assignee completes the work and <see cref="HumanActionCompleted"/> is raised, exactly once: completing a
    /// completed action is a no-op that keeps the first completion (Journey 14). Allowed from Accepted (workers may
    /// skip "start") or InProgress.
    /// </summary>
    /// <param name="staffMemberId">Who completed it; must be the assignee.</param>
    /// <param name="note">The worker's note; optional, at most 1000 characters.</param>
    /// <param name="evidence">Blob keys of photos or files; optional, at most 10.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a validation or <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Complete(StaffMemberId staffMemberId, string? note, IEnumerable<string>? evidence, DateTimeOffset now)
    {
        if (Status == HumanActionStatus.Completed)
        {
            return Result.Success();
        }

        if (AssignedTo != staffMemberId)
        {
            return NotAssigneeError();
        }

        if (Status is not (HumanActionStatus.Accepted or HumanActionStatus.InProgress))
        {
            return TransitionError("completed");
        }

        Result<HumanActionCompletion> completion = HumanActionRequestRules.ValidateCompletion(staffMemberId, note, evidence, now);

        if (completion.IsFailure)
        {
            return completion.Error;
        }

        Status = HumanActionStatus.Completed;
        StartedAt ??= now;
        Completion = completion.Value;
        Raise(new HumanActionCompleted(Id, staffMemberId, Details.ServiceRequestId, now));

        return Result.Success();
    }

    /// <summary>
    /// The assignee reports they cannot do the work and <see cref="HumanActionFailed"/> is raised (Journey 20).
    /// Failing a failed action is a no-op.
    /// </summary>
    /// <param name="staffMemberId">Who is failing it; must be the assignee.</param>
    /// <param name="reason">Why, e.g. "Could not access the room"; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a validation or <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Fail(StaffMemberId staffMemberId, string reason, DateTimeOffset now)
    {
        if (Status == HumanActionStatus.Failed)
        {
            return Result.Success();
        }

        if (AssignedTo != staffMemberId)
        {
            return NotAssigneeError();
        }

        if (Status is not (HumanActionStatus.Assigned or HumanActionStatus.Accepted or HumanActionStatus.InProgress))
        {
            return TransitionError("failed");
        }

        Result<string> validReason = HumanActionRequestRules.ValidateReason(reason);

        if (validReason.IsFailure)
        {
            return validReason.Error;
        }

        End(HumanActionStatus.Failed, validReason.Value, now);
        Raise(new HumanActionFailed(Id, staffMemberId, Details.ServiceRequestId, validReason.Value, now));

        return Result.Success();
    }

    /// <summary>
    /// Withdraws work that is no longer needed (e.g. the guest cancelled) and raises <see cref="HumanActionCancelled"/>.
    /// Cancelling a cancelled action is a no-op; work in progress cannot be cancelled (fail it instead).
    /// </summary>
    /// <param name="reason">Why; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a validation or <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Cancel(string reason, DateTimeOffset now)
    {
        if (Status == HumanActionStatus.Cancelled)
        {
            return Result.Success();
        }

        if (Status is not (HumanActionStatus.Requested or HumanActionStatus.Assigned or HumanActionStatus.Accepted))
        {
            return TransitionError("cancelled");
        }

        Result<string> validReason = HumanActionRequestRules.ValidateReason(reason);

        if (validReason.IsFailure)
        {
            return validReason.Error;
        }

        End(HumanActionStatus.Cancelled, validReason.Value, now);
        Raise(new HumanActionCancelled(Id, Details.ServiceRequestId, validReason.Value, now));

        return Result.Success();
    }

    /// <summary>
    /// Marks work that was never started as expired once its deadline has passed, and raises
    /// <see cref="HumanActionExpired"/>. Called by the scheduler; expiring an expired action is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error.</returns>
    public Result Expire(DateTimeOffset now)
    {
        if (Status == HumanActionStatus.Expired)
        {
            return Result.Success();
        }

        if (Status is not (HumanActionStatus.Requested or HumanActionStatus.Assigned or HumanActionStatus.Accepted))
        {
            return TransitionError("expired");
        }

        if (Deadline is null || now < Deadline)
        {
            return Error.InvalidState("human_action.deadline_not_passed", "The action has no deadline or it has not passed yet.");
        }

        End(HumanActionStatus.Expired, null, now);
        Raise(new HumanActionExpired(Id, Details.ServiceRequestId, now));

        return Result.Success();
    }

    private void End(HumanActionStatus status, string? reason, DateTimeOffset now)
    {
        Status = status;
        FailureReason = reason;
        EndedAt = now;
    }

    private Error TransitionError(string action) =>
        Error.InvalidState("human_action.transition_invalid", $"A {Status} action cannot be {action}.");

    private static Error NotAssigneeError() =>
        Error.InvalidState("human_action.not_assignee", "Only the assigned staff member can do this.");
}
