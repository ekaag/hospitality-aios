using HospitalityOS.Domain.Properties.Spaces.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.Spaces;

/// <summary>
/// A physical place within a property, arranged in a hierarchy (e.g. Main Building → Floor 4 → Room 412).
/// Other aggregates (amenities, restaurants, rooms, human actions) reference it as their location.
/// </summary>
/// <remarks>
/// The parent is fixed at creation and must already exist in the same property, so the hierarchy can
/// never contain a cycle. Re-parenting is deliberately not supported yet.
/// </remarks>
public sealed class Space : AggregateRoot<SpaceId>, ITenantScoped
{
    private Space(SpaceId id, TenantId tenantId, PropertyId propertyId, SpaceId? parentSpaceId, SpaceDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        ParentSpaceId = parentSpaceId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the space belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The containing space, or <c>null</c> for a top-level space.
    /// </summary>
    public SpaceId? ParentSpaceId { get; }

    /// <summary>
    /// Validated, normalized descriptive information.
    /// </summary>
    public SpaceDetails Details { get; private set; }

    /// <summary>
    /// Creates a space and raises <see cref="SpaceCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the space belongs to.</param>
    /// <param name="parent">The containing space, loaded by the caller; <c>null</c> for a top-level space.
    /// Must belong to the same property.</param>
    /// <param name="details">Descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The space, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Space> Create(
        SpaceId id,
        TenantId tenantId,
        PropertyId propertyId,
        Space? parent,
        SpaceDetails details,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        List<FieldError> errors = [];

        if (parent is not null && (parent.PropertyId != propertyId || parent.TenantId != tenantId))
        {
            errors.Add(new FieldError("parentSpaceId", "space.parent_other_property", "The parent space must belong to the same property."));
        }

        SpaceDetails? valid = Validate(details, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        // valid is non-null here: Validate only returns null after recording an error.
        Space space = new(id, tenantId, propertyId, parent?.Id, valid!);
        space.Raise(new SpaceCreated(id, propertyId, space.ParentSpaceId, space.Details, now));

        return space;
    }

    /// <summary>
    /// Replaces the descriptive information and raises <see cref="SpaceUpdated"/>. Updating to the current
    /// details is a successful no-op that raises nothing (P8).
    /// </summary>
    /// <param name="details">New descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(SpaceDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        List<FieldError> errors = [];
        SpaceDetails? valid = Validate(details, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        if (valid == Details)
        {
            return Result.Success();
        }

        Details = valid!;
        Raise(new SpaceUpdated(Id, Details, now));

        return Result.Success();
    }

    private static SpaceDetails? Validate(SpaceDetails details, List<FieldError> errors)
    {
        int errorCount = errors.Count;

        string name = TextRules.Required(details.Name, "name", "space.name", errors);
        string? code = TextRules.Optional(details.Code, "code", "space.code", errors, maxLength: 32);
        string? description = TextRules.Optional(details.Description, "description", "space.description", errors, TextRules.MaxLongTextLength);
        string? directions = TextRules.Optional(details.Directions, "directions", "space.directions", errors, TextRules.MaxLongTextLength);

        if (!Enum.IsDefined(details.Kind))
        {
            errors.Add(new FieldError("kind", "space.kind_invalid", $"'{details.Kind}' is not a known space kind."));
        }

        return errors.Count == errorCount ? new SpaceDetails(name, details.Kind, code, description, directions) : null;
    }
}
