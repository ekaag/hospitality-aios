using HospitalityOS.Domain.Properties.AccommodationTypes;
using HospitalityOS.Domain.Properties.AccommodationUnits.Events;
using HospitalityOS.Domain.Properties.Spaces;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.AccommodationUnits;

/// <summary>
/// An individual occupiable room, e.g. Room 412: an <see cref="AccommodationType"/> at a physical
/// <see cref="Space"/>. Guest stays and service requests reference it.
/// </summary>
/// <remarks>
/// Unit numbers must be unique within a property. That spans aggregates, so the application layer checks
/// it through <see cref="IAccommodationUnitRepository.FindByUnitNumberAsync"/> and persistence backs it
/// with a unique index.
/// </remarks>
public sealed class AccommodationUnit : AggregateRoot<AccommodationUnitId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Maximum length of <see cref="UnitNumber"/>.
    /// </summary>
    public const int MaxUnitNumberLength = 32;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private AccommodationUnit()
    {
        UnitNumber = null!;
    }

    private AccommodationUnit(
        AccommodationUnitId id,
        TenantId tenantId,
        PropertyId propertyId,
        AccommodationTypeId accommodationTypeId,
        SpaceId spaceId,
        string unitNumber)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        AccommodationTypeId = accommodationTypeId;
        SpaceId = spaceId;
        UnitNumber = unitNumber;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the unit belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// The unit's type, in the same property.
    /// </summary>
    public AccommodationTypeId AccommodationTypeId { get; private set; }

    /// <summary>
    /// Where the unit physically is, in the same property.
    /// </summary>
    public SpaceId SpaceId { get; }

    /// <summary>
    /// The number guests and staff use, e.g. <c>412</c>; trimmed.
    /// </summary>
    public string UnitNumber { get; private set; }

    /// <summary>
    /// Creates a unit and raises <see cref="AccommodationUnitCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="accommodationType">The unit's type, loaded by the caller; determines the property.</param>
    /// <param name="space">Where the unit is, loaded by the caller; must be in the same property.</param>
    /// <param name="unitNumber">The number guests and staff use; required.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The unit, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<AccommodationUnit> Create(
        AccommodationUnitId id,
        AccommodationType accommodationType,
        Space space,
        string unitNumber,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(accommodationType);
        ArgumentNullException.ThrowIfNull(space);

        List<FieldError> errors = [];
        string number = ValidateUnitNumber(unitNumber, errors);

        if (!InSameProperty(accommodationType, space))
        {
            errors.Add(new FieldError("spaceId", "accommodation_unit.space_other_property", "The space must belong to the same property as the accommodation type."));
        }

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        AccommodationUnit unit = new(id, accommodationType.TenantId, accommodationType.PropertyId, accommodationType.Id, space.Id, number);
        unit.Raise(new AccommodationUnitCreated(id, unit.PropertyId, unit.AccommodationTypeId, unit.SpaceId, unit.UnitNumber, now));

        return unit;
    }

    /// <summary>
    /// Changes the unit number and raises <see cref="AccommodationUnitUpdated"/>. Renumbering to the current
    /// number is a successful no-op that raises nothing (P8).
    /// </summary>
    /// <param name="unitNumber">The new number; required. The caller checks uniqueness within the property.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/>.</returns>
    public Result Renumber(string unitNumber, DateTimeOffset now)
    {
        List<FieldError> errors = [];
        string number = ValidateUnitNumber(unitNumber, errors);

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        if (number == UnitNumber)
        {
            return Result.Success();
        }

        UnitNumber = number;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Changes the unit's type and raises <see cref="AccommodationUnitUpdated"/>. Changing to the current
    /// type is a successful no-op that raises nothing (P8).
    /// </summary>
    /// <param name="accommodationType">The new type, loaded by the caller; must be in the same property.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/>.</returns>
    public Result ChangeType(AccommodationType accommodationType, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(accommodationType);

        if (accommodationType.PropertyId != PropertyId || accommodationType.TenantId != TenantId)
        {
            return Error.Validation("accommodationTypeId", "accommodation_unit.type_other_property", "The accommodation type must belong to the unit's property.");
        }

        if (accommodationType.Id == AccommodationTypeId)
        {
            return Result.Success();
        }

        AccommodationTypeId = accommodationType.Id;
        RaiseUpdated(now);

        return Result.Success();
    }

    private static bool InSameProperty(AccommodationType accommodationType, Space space) =>
        accommodationType.PropertyId == space.PropertyId && accommodationType.TenantId == space.TenantId;

    private static string ValidateUnitNumber(string? unitNumber, List<FieldError> errors) =>
        TextRules.Required(unitNumber, "unitNumber", "accommodation_unit.unit_number", errors, MaxUnitNumberLength);

    private void RaiseUpdated(DateTimeOffset now) =>
        Raise(new AccommodationUnitUpdated(Id, AccommodationTypeId, UnitNumber, now));
}
