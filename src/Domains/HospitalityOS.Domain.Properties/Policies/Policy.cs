using HospitalityOS.Domain.Properties.Policies.Events;
using HospitalityOS.Domain.Properties.Shared;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.Policies;

/// <summary>
/// An authoritative rule of the property, e.g. "children under 16 must be accompanied in the gym". Kept
/// separate from descriptive <see cref="ContentItems.ContentItem"/>s so the concierge answers policy questions only
/// from policy, and says it does not know when no policy exists (Journeys 4 and 6, P4).
/// </summary>
public sealed class Policy : AggregateRoot<PolicyId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Maximum length of <see cref="PolicyDetails.Content"/>.
    /// </summary>
    public const int MaxContentLength = 4000;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private Policy()
    {
        Details = null!;
    }

    private Policy(PolicyId id, TenantId tenantId, PropertyId propertyId, PolicyDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
        Status = PolicyStatus.Draft;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the policy belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized content.
    /// </summary>
    public PolicyDetails Details { get; private set; }

    /// <summary>
    /// Where the policy is in its lifecycle.
    /// </summary>
    public PolicyStatus Status { get; private set; }

    /// <summary>
    /// Creates a draft policy and raises <see cref="PolicyCreated"/>. Call <see cref="Activate"/> to put it in force.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the policy belongs to.</param>
    /// <param name="details">Content; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The policy, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Policy> Create(PolicyId id, TenantId tenantId, PropertyId propertyId, PolicyDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<PolicyDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Policy policy = new(id, tenantId, propertyId, valid.Value);
        policy.Raise(new PolicyCreated(id, propertyId, policy.Details, policy.Status, now));

        return policy;
    }

    /// <summary>
    /// Replaces the content and raises <see cref="PolicyUpdated"/>. A no-change update is a successful no-op (P8).
    /// </summary>
    /// <param name="details">New content; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, a <see cref="ValidationError"/>, or an <see cref="ErrorKind.InvalidState"/> error when retired.</returns>
    public Result Update(PolicyDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        if (Status == PolicyStatus.Retired)
        {
            return RetiredError("updated");
        }

        Result<PolicyDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Puts a draft policy in force and raises <see cref="PolicyUpdated"/>. Activating an active policy is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or an <see cref="ErrorKind.InvalidState"/> error when retired.</returns>
    public Result Activate(DateTimeOffset now) => TransitionTo(PolicyStatus.Active, now);

    /// <summary>
    /// Takes the policy out of force permanently and raises <see cref="PolicyUpdated"/>. Retiring twice is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success.</returns>
    public Result Retire(DateTimeOffset now) => TransitionTo(PolicyStatus.Retired, now);

    /// <summary>
    /// Whether the policy governs guests on a property-local date: active and within its effective dates.
    /// </summary>
    /// <param name="localDate">The date in property-local time.</param>
    public bool IsInEffectOn(DateOnly localDate) =>
        Status == PolicyStatus.Active
        && (Details.EffectiveFrom is null || Details.EffectiveFrom <= localDate)
        && (Details.EffectiveTo is null || Details.EffectiveTo >= localDate);

    private Result TransitionTo(PolicyStatus target, DateTimeOffset now)
    {
        if (Status == target)
        {
            return Result.Success();
        }

        if (Status == PolicyStatus.Retired)
        {
            return RetiredError("reactivated");
        }

        Status = target;
        RaiseUpdated(now);

        return Result.Success();
    }

    private static Error RetiredError(string action) =>
        Error.InvalidState("policy.retired", $"A retired policy cannot be {action}; create a new policy instead.");

    private void RaiseUpdated(DateTimeOffset now) => Raise(new PolicyUpdated(Id, Details, Status, now));

    private static Result<PolicyDetails> Validate(PolicyDetails details)
    {
        List<FieldError> errors = [];

        string title = TextRules.Required(details.Title, "title", "policy.title", errors);
        string content = TextRules.Required(details.Content, "content", "policy.content", errors, MaxContentLength);

        if (!Enum.IsDefined(details.Type))
        {
            errors.Add(new FieldError("type", "policy.type_invalid", $"'{details.Type}' is not a known policy type."));
        }

        if (details.EffectiveFrom is not null && details.EffectiveTo is not null && details.EffectiveTo < details.EffectiveFrom)
        {
            errors.Add(new FieldError("effectiveTo", "policy.effective_range_invalid", "effectiveTo must be on or after effectiveFrom."));
        }

        if (details.AppliesTo is not null)
        {
            SubjectReferenceRules.Validate(details.AppliesTo, "appliesTo", "policy.applies_to", errors);
        }

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Title = title, Content = content };
    }
}
