using HospitalityOS.Domain.Properties.Properties.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Properties.Properties;

/// <summary>
/// One hotel. Owns its base information; spaces, amenities, hours, and policies are separate
/// aggregates that reference it by <see cref="PropertyId"/>.
/// </summary>
public sealed class Property : AggregateRoot<PropertyId>, ITenantScoped
{
    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private Property()
    {
        Details = null!;
    }

    private Property(PropertyId id, TenantId tenantId, OrganizationId organizationId, PropertyDetails details)
        : base(id)
    {
        TenantId = tenantId;
        OrganizationId = organizationId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The organization that owns or operates the property.
    /// </summary>
    public OrganizationId OrganizationId { get; }

    /// <summary>
    /// Validated, normalized base information.
    /// </summary>
    public PropertyDetails Details { get; private set; }

    /// <summary>
    /// Creates a property and raises <see cref="PropertyCreated"/> (Journey 1).
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="organizationId">The owning organization, in the same tenant.</param>
    /// <param name="details">Base information; validated and normalized (trimmed, country code upper-cased).</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The property, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Property> Create(
        PropertyId id,
        TenantId tenantId,
        OrganizationId organizationId,
        PropertyDetails details,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<PropertyDetails> valid = PropertyDetailsRules.Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Property property = new(id, tenantId, organizationId, valid.Value);
        property.Raise(new PropertyCreated(id, organizationId, property.Details, now));

        return property;
    }

    /// <summary>
    /// Replaces the base information and raises <see cref="PropertyUpdated"/>. Updating to the current
    /// details is a successful no-op that raises nothing, so retried requests are harmless (P8).
    /// </summary>
    /// <param name="details">New base information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(PropertyDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<PropertyDetails> valid = PropertyDetailsRules.Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        Raise(new PropertyUpdated(Id, Details, now));

        return Result.Success();
    }
}
