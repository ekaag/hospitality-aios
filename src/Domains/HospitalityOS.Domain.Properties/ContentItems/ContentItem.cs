using HospitalityOS.Domain.Properties.ContentItems.Events;
using HospitalityOS.Domain.Properties.Shared;
using HospitalityOS.SharedKernel.Collections;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.ContentItems;

/// <summary>
/// Descriptive property content — overviews, FAQs, directions, announcements — that the concierge searches
/// (<c>Property.SearchContent</c>). Not authoritative for rules: those are <see cref="Policies.Policy"/> records.
/// </summary>
public sealed class ContentItem : AggregateRoot<ContentItemId>, ITenantScoped, IPropertyScoped
{
    /// <summary>
    /// Maximum length of <see cref="ContentItemDetails.Body"/>.
    /// </summary>
    public const int MaxBodyLength = 8000;

    /// <summary>
    /// Maximum number of tags.
    /// </summary>
    public const int MaxTags = 20;

    private const int MaxTagLength = 50;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private ContentItem()
    {
        Details = null!;
    }

    private ContentItem(ContentItemId id, TenantId tenantId, PropertyId propertyId, ContentItemDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
        Status = ContentStatus.Draft;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property the content belongs to.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized text. <see cref="ContentItemDetails.Tags"/> is never <c>null</c> here.
    /// </summary>
    public ContentItemDetails Details { get; private set; }

    /// <summary>
    /// Where the item is in its lifecycle.
    /// </summary>
    public ContentStatus Status { get; private set; }

    /// <summary>
    /// Creates a draft content item and raises <see cref="ContentItemCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the content belongs to.</param>
    /// <param name="details">Text; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The content item, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<ContentItem> Create(ContentItemId id, TenantId tenantId, PropertyId propertyId, ContentItemDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<ContentItemDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        ContentItem item = new(id, tenantId, propertyId, valid.Value);
        item.Raise(new ContentItemCreated(id, propertyId, item.Details, item.Status, now));

        return item;
    }

    /// <summary>
    /// Replaces the text and raises <see cref="ContentItemUpdated"/>. A no-change update is a successful no-op (P8).
    /// </summary>
    /// <param name="details">New text; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(ContentItemDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<ContentItemDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        RaiseUpdated(now);

        return Result.Success();
    }

    /// <summary>
    /// Makes the item visible to guests and the concierge; publishing published content is a no-op.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success.</returns>
    public Result Publish(DateTimeOffset now) => TransitionTo(ContentStatus.Published, now);

    /// <summary>
    /// Withdraws the item; archiving archived content is a no-op. Archived content can be published again.
    /// </summary>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success.</returns>
    public Result Archive(DateTimeOffset now) => TransitionTo(ContentStatus.Archived, now);

    private Result TransitionTo(ContentStatus target, DateTimeOffset now)
    {
        if (Status != target)
        {
            Status = target;
            RaiseUpdated(now);
        }

        return Result.Success();
    }

    private void RaiseUpdated(DateTimeOffset now) => Raise(new ContentItemUpdated(Id, Details, Status, now));

    private static Result<ContentItemDetails> Validate(ContentItemDetails details)
    {
        List<FieldError> errors = [];

        string title = TextRules.Required(details.Title, "title", "content.title", errors);
        string body = TextRules.Required(details.Body, "body", "content.body", errors, MaxBodyLength);
        ValueList<string> tags = NormalizeTags(details.Tags ?? [], errors);

        if (!Enum.IsDefined(details.Type))
        {
            errors.Add(new FieldError("type", "content.type_invalid", $"'{details.Type}' is not a known content type."));
        }

        if (details.About is not null)
        {
            SubjectReferenceRules.Validate(details.About, "about", "content.about", errors);
        }

        return errors.Count > 0
            ? ValidationError.From(errors)
            : details with { Title = title, Body = body, Tags = tags };
    }

    private static ValueList<string> NormalizeTags(ValueList<string> tags, List<FieldError> errors)
    {
        SortedSet<string> normalized = new(StringComparer.Ordinal);

        for (int i = 0; i < tags.Count; i++)
        {
            string tag = TextRules.Required(tags[i], $"tags[{i}]", "content.tag", errors, MaxTagLength).ToLowerInvariant();

            if (tag.Length > 0)
            {
                normalized.Add(tag);
            }
        }

        if (normalized.Count > MaxTags)
        {
            errors.Add(new FieldError("tags", "content.too_many_tags", $"At most {MaxTags} tags are allowed."));
        }

        return ValueList.From(normalized);
    }
}
