using HospitalityOS.Domain.Properties.Hours.Events;
using HospitalityOS.SharedKernel.Collections;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;

namespace HospitalityOS.Domain.Properties.Hours;

/// <summary>
/// The opening hours of one subject (the property, a space, an amenity, a restaurant, or a service), in
/// property-local time. Answers "what are the pool hours tonight?" and "is the gym open now?" from
/// authoritative data, and its <see cref="AggregateRoot{TId}.Version"/> is what grounded answers cite (P4).
/// </summary>
public sealed class OperatingHours : AggregateRoot<OperatingHoursId>, ITenantScoped
{
    private OperatingHours(OperatingHoursId id, TenantId tenantId, PropertyId propertyId, HoursSubject subject, OperatingHoursSchedule schedule)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Subject = subject;
        Schedule = schedule;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property whose local time the schedule uses.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// What the hours describe. Fixed at creation; one record per subject (checked by the application layer).
    /// </summary>
    public HoursSubject Subject { get; }

    /// <summary>
    /// The validated, normalized schedule.
    /// </summary>
    public OperatingHoursSchedule Schedule { get; private set; }

    /// <summary>
    /// Creates operating hours and raises <see cref="OperatingHoursCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property the subject belongs to.</param>
    /// <param name="subject">What the hours describe.</param>
    /// <param name="schedule">The schedule; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The operating hours, or a <see cref="ValidationError"/> listing every problem.</returns>
    public static Result<OperatingHours> Create(
        OperatingHoursId id,
        TenantId tenantId,
        PropertyId propertyId,
        HoursSubject subject,
        OperatingHoursSchedule schedule,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(subject);
        ArgumentNullException.ThrowIfNull(schedule);

        List<FieldError> errors = [];

        if (!Enum.IsDefined(subject.Kind))
        {
            errors.Add(new FieldError("subject.kind", "hours.subject_kind_invalid", $"'{subject.Kind}' is not a known subject kind."));
        }

        if (subject.Id == Guid.Empty)
        {
            errors.Add(new FieldError("subject.id", "hours.subject_id_required", "subject.id is required."));
        }

        Result<OperatingHoursSchedule> valid = OperatingHoursScheduleRules.Validate(schedule);

        if (valid.IsFailure)
        {
            errors.AddRange(((ValidationError)valid.Error).Fields);
        }

        if (errors.Count > 0)
        {
            return ValidationError.From(errors);
        }

        OperatingHours hours = new(id, tenantId, propertyId, subject, valid.Value);
        hours.Raise(new OperatingHoursCreated(id, propertyId, subject, hours.Schedule, now));

        return hours;
    }

    /// <summary>
    /// Replaces the schedule and raises <see cref="OperatingHoursUpdated"/> (Journey 16). Replacing it with an
    /// equivalent schedule is a successful no-op that raises nothing and keeps the version (P8).
    /// </summary>
    /// <param name="schedule">The new schedule; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every problem.</returns>
    public Result Update(OperatingHoursSchedule schedule, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(schedule);

        Result<OperatingHoursSchedule> valid = OperatingHoursScheduleRules.Validate(schedule);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Schedule)
        {
            return Result.Success();
        }

        Schedule = valid.Value;
        Raise(new OperatingHoursUpdated(Id, Schedule, now));

        return Result.Success();
    }

    /// <summary>
    /// The hours that apply on a property-local date: a closure, else an override, else the weekly hours.
    /// </summary>
    /// <param name="localDate">The date in property-local time.</param>
    /// <returns>The periods opening that date and which rule decided.</returns>
    public HoursForDate GetHoursFor(DateOnly localDate)
    {
        TemporaryClosure? closure = Schedule.Closures.FirstOrDefault(candidate => candidate.Covers(localDate));

        if (closure is not null)
        {
            return new HoursForDate(localDate, HoursSource.Closure, [], closure.Reason);
        }

        DateOverride? dateOverride = Schedule.Overrides.FirstOrDefault(candidate => candidate.Date == localDate);

        if (dateOverride is not null)
        {
            return new HoursForDate(localDate, HoursSource.Override, PeriodsOn(localDate, dateOverride.Intervals), dateOverride.Note);
        }

        DayHours? day = Schedule.Weekly.FirstOrDefault(candidate => candidate.Day == localDate.DayOfWeek);

        return new HoursForDate(localDate, HoursSource.Weekly, PeriodsOn(localDate, day?.Intervals ?? []));
    }

    /// <summary>
    /// Whether the subject is open at an instant, including overnight hours that began the previous day.
    /// </summary>
    /// <param name="instant">The moment to check, e.g. now from the injected <see cref="TimeProvider"/>.</param>
    /// <param name="propertyTimeZone">The property's time zone (from <c>Property.Details.TimeZoneId</c>).</param>
    /// <returns>The local time and the open period, if any.</returns>
    public OpenStatus GetStatusAt(DateTimeOffset instant, TimeZoneInfo propertyTimeZone)
    {
        ArgumentNullException.ThrowIfNull(propertyTimeZone);

        DateTime localTime = TimeZoneInfo.ConvertTime(instant, propertyTimeZone).DateTime;
        DateOnly localDate = DateOnly.FromDateTime(localTime);

        OpenPeriod? current = GetHoursFor(localDate.AddDays(-1)).Periods
            .Concat(GetHoursFor(localDate).Periods)
            .FirstOrDefault(period => period.Contains(localTime));

        return new OpenStatus(localTime, current);
    }

    private static ValueList<OpenPeriod> PeriodsOn(DateOnly date, ValueList<TimeInterval> intervals) =>
        ValueList.From(intervals.Select(interval => interval.On(date)));
}
