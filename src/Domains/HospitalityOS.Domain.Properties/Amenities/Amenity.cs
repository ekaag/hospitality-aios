using HospitalityOS.Domain.Properties.Amenities.Events;
using HospitalityOS.Domain.Properties.Spaces;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.Amenities;

/// <summary>
/// A facility guests can use, e.g. the pool or the gym (Journey 2). Its hours are an
/// <see cref="Hours.OperatingHours"/> record and its rules are <see cref="Policies.Policy"/> records,
/// both referring to it by subject.
/// </summary>
public sealed class Amenity : AggregateRoot<AmenityId>, ITenantScoped
{
    private Amenity(AmenityId id, TenantId tenantId, PropertyId propertyId, AmenityDetails details, SpaceId? locationSpaceId)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
        LocationSpaceId = locationSpaceId;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property offering the amenity.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized descriptive information.
    /// </summary>
    public AmenityDetails Details { get; private set; }

    /// <summary>
    /// Where the amenity is, if recorded; a space in the same property.
    /// </summary>
    public SpaceId? LocationSpaceId { get; private set; }

    /// <summary>
    /// Creates an amenity and raises <see cref="AmenityCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property offering the amenity.</param>
    /// <param name="details">Descriptive information; validated and normalized.</param>
    /// <param name="location">Where it is, loaded by the caller; must be in the same property. Optional.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The amenity, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<Amenity> Create(
        AmenityId id,
        TenantId tenantId,
        PropertyId propertyId,
        AmenityDetails details,
        Space? location,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<AmenityDetails> valid = Validate(details, location, tenantId, propertyId);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        Amenity amenity = new(id, tenantId, propertyId, valid.Value, location?.Id);
        amenity.Raise(new AmenityCreated(id, propertyId, amenity.Details, amenity.LocationSpaceId, now));

        return amenity;
    }

    /// <summary>
    /// Replaces the descriptive information and location and raises <see cref="AmenityUpdated"/>. An update
    /// that changes nothing is a successful no-op that raises nothing (P8).
    /// </summary>
    /// <param name="details">New descriptive information; validated and normalized.</param>
    /// <param name="location">New location, loaded by the caller; <c>null</c> clears it.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(AmenityDetails details, Space? location, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<AmenityDetails> valid = Validate(details, location, TenantId, PropertyId);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details && location?.Id == LocationSpaceId)
        {
            return Result.Success();
        }

        Details = valid.Value;
        LocationSpaceId = location?.Id;
        Raise(new AmenityUpdated(Id, Details, LocationSpaceId, now));

        return Result.Success();
    }

    private static Result<AmenityDetails> Validate(AmenityDetails details, Space? location, TenantId tenantId, PropertyId propertyId)
    {
        List<FieldError> errors = [];

        string name = TextRules.Required(details.Name, "name", "amenity.name", errors);
        string? description = TextRules.Optional(details.Description, "description", "amenity.description", errors, TextRules.MaxLongTextLength);

        if (!Enum.IsDefined(details.Category))
        {
            errors.Add(new FieldError("category", "amenity.category_invalid", $"'{details.Category}' is not a known amenity category."));
        }

        if (location is not null && (location.PropertyId != propertyId || location.TenantId != tenantId))
        {
            errors.Add(new FieldError("locationSpaceId", "amenity.location_other_property", "The location must be a space in the same property."));
        }

        return errors.Count > 0 ? ValidationError.From(errors) : new AmenityDetails(name, details.Category, description);
    }
}
