using HospitalityOS.Domain.Properties.AccommodationTypes.Events;
using HospitalityOS.SharedKernel.Domain;
using HospitalityOS.SharedKernel.Ids;
using HospitalityOS.SharedKernel.Results;
using HospitalityOS.SharedKernel.Tenancy;
using HospitalityOS.SharedKernel.Validation;

namespace HospitalityOS.Domain.Properties.AccommodationTypes;

/// <summary>
/// A category of room a property offers, e.g. Deluxe King. Individual rooms are
/// <see cref="AccommodationUnits.AccommodationUnit"/>s of a type.
/// </summary>
public sealed class AccommodationType : AggregateRoot<AccommodationTypeId>, ITenantScoped
{
    /// <summary>
    /// Upper bound for <see cref="AccommodationTypeDetails.MaxOccupancy"/>; guards against typos, not real limits.
    /// </summary>
    public const int MaxAllowedOccupancy = 50;

    // For EF Core only: it sets every property from storage before the instance is used, so the
    // placeholders below are never read.
    private AccommodationType()
    {
        Details = null!;
    }

    private AccommodationType(AccommodationTypeId id, TenantId tenantId, PropertyId propertyId, AccommodationTypeDetails details)
        : base(id)
    {
        TenantId = tenantId;
        PropertyId = propertyId;
        Details = details;
    }

    /// <inheritdoc />
    public TenantId TenantId { get; }

    /// <summary>
    /// The property offering this type.
    /// </summary>
    public PropertyId PropertyId { get; }

    /// <summary>
    /// Validated, normalized descriptive information.
    /// </summary>
    public AccommodationTypeDetails Details { get; private set; }

    /// <summary>
    /// Creates an accommodation type and raises <see cref="AccommodationTypeCreated"/>.
    /// </summary>
    /// <param name="id">New ID, generated by the caller through <c>IIdGenerator</c>.</param>
    /// <param name="tenantId">The owning tenant.</param>
    /// <param name="propertyId">The property offering the type.</param>
    /// <param name="details">Descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>The accommodation type, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public static Result<AccommodationType> Create(
        AccommodationTypeId id,
        TenantId tenantId,
        PropertyId propertyId,
        AccommodationTypeDetails details,
        DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<AccommodationTypeDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        AccommodationType type = new(id, tenantId, propertyId, valid.Value);
        type.Raise(new AccommodationTypeCreated(id, propertyId, type.Details, now));

        return type;
    }

    /// <summary>
    /// Replaces the descriptive information and raises <see cref="AccommodationTypeUpdated"/>. Updating to
    /// the current details is a successful no-op that raises nothing (P8).
    /// </summary>
    /// <param name="details">New descriptive information; validated and normalized.</param>
    /// <param name="now">Current time from the injected <see cref="TimeProvider"/>.</param>
    /// <returns>Success, or a <see cref="ValidationError"/> listing every invalid field.</returns>
    public Result Update(AccommodationTypeDetails details, DateTimeOffset now)
    {
        ArgumentNullException.ThrowIfNull(details);

        Result<AccommodationTypeDetails> valid = Validate(details);

        if (valid.IsFailure)
        {
            return valid.Error;
        }

        if (valid.Value == Details)
        {
            return Result.Success();
        }

        Details = valid.Value;
        Raise(new AccommodationTypeUpdated(Id, Details, now));

        return Result.Success();
    }

    private static Result<AccommodationTypeDetails> Validate(AccommodationTypeDetails details)
    {
        List<FieldError> errors = [];

        string name = TextRules.Required(details.Name, "name", "accommodation_type.name", errors);
        string? description = TextRules.Optional(details.Description, "description", "accommodation_type.description", errors, TextRules.MaxLongTextLength);

        if (details.MaxOccupancy is < 1 or > MaxAllowedOccupancy)
        {
            errors.Add(new FieldError("maxOccupancy", "accommodation_type.max_occupancy_out_of_range", $"Max occupancy must be between 1 and {MaxAllowedOccupancy}."));
        }

        return errors.Count > 0
            ? ValidationError.From(errors)
            : new AccommodationTypeDetails(name, details.MaxOccupancy, description);
    }
}
